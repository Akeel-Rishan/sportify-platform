CREATE TABLE BUSINESSES (
    BUSINESS_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    BUSINESS_NAME VARCHAR2(200 CHAR) NOT NULL,
    BUSINESS_SLUG VARCHAR2(100 CHAR) NOT NULL,
    LEGAL_NAME VARCHAR2(200 CHAR),
    BUSINESS_STATUS VARCHAR2(20 CHAR) DEFAULT 'SETUP' NOT NULL,
    CONTACT_EMAIL VARCHAR2(320 CHAR),
    CONTACT_MOBILE VARCHAR2(16 CHAR),
    COUNTRY_CODE CHAR(2 CHAR) DEFAULT 'LK' NOT NULL,
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    UPDATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    CONSTRAINT PK_BUSINESSES PRIMARY KEY (BUSINESS_ID),
    CONSTRAINT UQ_BUSINESSES_TENANT_ID UNIQUE (TENANT_ID, BUSINESS_ID),
    CONSTRAINT UQ_BUSINESSES_ONE_PER_TENANT UNIQUE (TENANT_ID),
    CONSTRAINT UQ_BUSINESSES_SLUG UNIQUE (BUSINESS_SLUG),
    CONSTRAINT UQ_BUSINESSES_PUBLIC_ID UNIQUE (TENANT_ID, PUBLIC_ID),
    CONSTRAINT CK_BUSINESSES_STATUS CHECK (business_status IN ('SETUP','ACTIVE','SUSPENDED','CLOSED')),
    CONSTRAINT CK_BUSINESSES_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_BUSINESSES_ID_POSITIVE CHECK (BUSINESS_ID>0 AND BUSINESS_ID=TRUNC(BUSINESS_ID))
)
