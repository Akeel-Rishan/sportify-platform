CREATE TABLE BUSINESS_SPORTS (
    TENANT_ID NUMBER NOT NULL,
    BUSINESS_ID NUMBER NOT NULL,
    SPORT_ID NUMBER NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    ENABLED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT PK_BUSINESS_SPORTS PRIMARY KEY (TENANT_ID, BUSINESS_ID, SPORT_ID),
    CONSTRAINT CK_BUSINESS_SPORTS_STATUS CHECK (status IN ('ACTIVE','INACTIVE'))
)
