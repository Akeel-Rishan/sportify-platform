CREATE TABLE LOCATIONS (
    LOCATION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    BUSINESS_ID NUMBER NOT NULL,
    LOCATION_CODE VARCHAR2(40 CHAR) NOT NULL,
    LOCATION_NAME VARCHAR2(180 CHAR) NOT NULL,
    PHONE_E164 VARCHAR2(16 CHAR),
    EMAIL VARCHAR2(320 CHAR),
    ADDRESS_LINE_1 VARCHAR2(200 CHAR) NOT NULL,
    ADDRESS_LINE_2 VARCHAR2(200 CHAR),
    CITY VARCHAR2(100 CHAR) NOT NULL,
    DISTRICT VARCHAR2(100 CHAR),
    POSTAL_CODE VARCHAR2(20 CHAR),
    COUNTRY_CODE CHAR(2 CHAR) DEFAULT 'LK' NOT NULL,
    TIMEZONE_NAME VARCHAR2(64 CHAR) DEFAULT 'Asia/Colombo' NOT NULL,
    LATITUDE NUMBER(10,7),
    LONGITUDE NUMBER(10,7),
    LOCATION_STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    UPDATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    CONSTRAINT PK_LOCATIONS PRIMARY KEY (LOCATION_ID),
    CONSTRAINT UQ_LOCATIONS_TENANT_ID UNIQUE (TENANT_ID, LOCATION_ID),
    CONSTRAINT UQ_LOCATIONS_BUSINESS_LOCATION UNIQUE (TENANT_ID, BUSINESS_ID, LOCATION_ID),
    CONSTRAINT UQ_LOCATIONS_BUSINESS_CODE UNIQUE (TENANT_ID, BUSINESS_ID, LOCATION_CODE),
    CONSTRAINT UQ_LOCATIONS_PUBLIC_ID UNIQUE (TENANT_ID, PUBLIC_ID),
    CONSTRAINT CK_LOCATIONS_STATUS CHECK (location_status IN ('ACTIVE','INACTIVE','CLOSED')),
    CONSTRAINT CK_LOCATIONS_LAT CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT CK_LOCATIONS_LON CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    CONSTRAINT CK_LOCATIONS_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_LOCATIONS_ID_POSITIVE CHECK (LOCATION_ID>0 AND LOCATION_ID=TRUNC(LOCATION_ID))
)
