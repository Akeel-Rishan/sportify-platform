CREATE TABLE BUSINESS_PROFILES (
    BUSINESS_PROFILE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    BUSINESS_ID NUMBER NOT NULL,
    DESCRIPTION CLOB,
    ADDRESS_LINE_1 VARCHAR2(200 CHAR),
    ADDRESS_LINE_2 VARCHAR2(200 CHAR),
    CITY VARCHAR2(100 CHAR),
    DISTRICT VARCHAR2(100 CHAR),
    POSTAL_CODE VARCHAR2(20 CHAR),
    COUNTRY_CODE CHAR(2 CHAR) DEFAULT 'LK' NOT NULL,
    LATITUDE NUMBER(10,7),
    LONGITUDE NUMBER(10,7),
    WEBSITE_URL VARCHAR2(500 CHAR),
    FACEBOOK_URL VARCHAR2(500 CHAR),
    INSTAGRAM_URL VARCHAR2(500 CHAR),
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    UPDATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT PK_BUSINESS_PROFILES PRIMARY KEY (BUSINESS_PROFILE_ID),
    CONSTRAINT UQ_BUSINESS_PROFILES_BUSINESS UNIQUE (TENANT_ID, BUSINESS_ID),
    CONSTRAINT CK_BUSINESS_PROFILES_LAT CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT CK_BUSINESS_PROFILES_LON CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    CONSTRAINT CK_BUSINESS_PROFILES_ID_POSITIVE CHECK (BUSINESS_PROFILE_ID>0 AND BUSINESS_PROFILE_ID=TRUNC(BUSINESS_PROFILE_ID))
)
