CREATE TABLE SUBSCRIPTION_PAYMENTS (
    SUBSCRIPTION_PAYMENT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    SUBSCRIPTION_INVOICE_ID NUMBER NOT NULL,
    PAYMENT_METHOD VARCHAR2(30 CHAR) NOT NULL,
    AMOUNT NUMBER(12,2) NOT NULL,
    CURRENCY_CODE CHAR(3 CHAR) NOT NULL,
    PAYMENT_REFERENCE VARCHAR2(160 CHAR),
    PAYMENT_STATUS VARCHAR2(20 CHAR) DEFAULT 'RECEIVED' NOT NULL,
    RECEIVED_AT_UTC TIMESTAMP(6) NOT NULL,
    RECORDED_BY_USER_ID NUMBER NOT NULL,
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    VOIDED_AT_UTC TIMESTAMP(6),
    VOID_REASON VARCHAR2(1000 CHAR),
    VOIDED_BY_USER_ID NUMBER,
    RECORDED_BY_PLATFORM_ADMIN_ID NUMBER NOT NULL,
    VOIDED_BY_PLATFORM_ADMIN_ID NUMBER,
    CONSTRAINT PK_SUBSCRIPTION_PAYMENTS PRIMARY KEY (SUBSCRIPTION_PAYMENT_ID),
    CONSTRAINT UQ_SP_TENANT_ID UNIQUE (TENANT_ID, SUBSCRIPTION_PAYMENT_ID),
    CONSTRAINT UQ_SUBSCRIPTION_PAYMENTS_PUBLIC_ID UNIQUE (TENANT_ID, PUBLIC_ID),
    CONSTRAINT CK_SP_METHOD CHECK (payment_method IN ('CASH','BANK_TRANSFER','CARD','OTHER')),
    CONSTRAINT CK_SP_STATUS CHECK (payment_status IN ('RECEIVED','VOIDED')),
    CONSTRAINT CK_SP_AMOUNT CHECK (amount > 0),
    CONSTRAINT CK_SUBSCRIPTION_PAYMENTS_CURRENCY_CODE CHECK (REGEXP_LIKE(CURRENCY_CODE,'^[A-Z]{3}$','c')),
    CONSTRAINT CK_SUBSCRIPTION_PAYMENTS_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_SUBSCRIPTION_PAYMENTS_ID_POSITIVE CHECK (SUBSCRIPTION_PAYMENT_ID>0 AND SUBSCRIPTION_PAYMENT_ID=TRUNC(SUBSCRIPTION_PAYMENT_ID)),
    CONSTRAINT CK_SUBSCRIPTION_PAYMENTS_VOID CHECK ((payment_status='RECEIVED' AND voided_at_utc IS NULL AND void_reason IS NULL AND voided_by_user_id IS NULL AND voided_by_platform_admin_id IS NULL) OR (payment_status='VOIDED' AND voided_at_utc IS NOT NULL AND void_reason IS NOT NULL AND voided_by_user_id IS NOT NULL AND voided_by_platform_admin_id IS NOT NULL))
)
