CREATE TABLE SUBSCRIPTION_INVOICES (
    SUBSCRIPTION_INVOICE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    SUBSCRIPTION_ID NUMBER NOT NULL,
    INVOICE_NUMBER VARCHAR2(50 CHAR) NOT NULL,
    AMOUNT_DUE NUMBER(12,2) NOT NULL,
    CURRENCY_CODE CHAR(3 CHAR) NOT NULL,
    INVOICE_STATUS VARCHAR2(20 CHAR) DEFAULT 'ISSUED' NOT NULL,
    ISSUED_AT_UTC TIMESTAMP(6) NOT NULL,
    DUE_AT_UTC TIMESTAMP(6),
    PAID_AT_UTC TIMESTAMP(6),
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    PERIOD_STARTS_AT_UTC TIMESTAMP(6) NOT NULL,
    PERIOD_ENDS_AT_UTC TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_SUBSCRIPTION_INVOICES PRIMARY KEY (SUBSCRIPTION_INVOICE_ID),
    CONSTRAINT UQ_SI_TENANT_ID UNIQUE (TENANT_ID, SUBSCRIPTION_INVOICE_ID),
    CONSTRAINT UQ_SI_NUMBER UNIQUE (TENANT_ID, INVOICE_NUMBER),
    CONSTRAINT UQ_INVOICE_CURRENCY UNIQUE (TENANT_ID, SUBSCRIPTION_INVOICE_ID, CURRENCY_CODE),
    CONSTRAINT CK_SI_AMOUNT CHECK (amount_due >= 0),
    CONSTRAINT CK_SI_STATUS CHECK (invoice_status IN ('DRAFT','ISSUED','PAID','OVERDUE','VOID')),
    CONSTRAINT CK_SUBSCRIPTION_INVOICES_CURRENCY_CODE CHECK (REGEXP_LIKE(CURRENCY_CODE,'^[A-Z]{3}$','c')),
    CONSTRAINT CK_SUBSCRIPTION_INVOICES_ID_POSITIVE CHECK (SUBSCRIPTION_INVOICE_ID>0 AND SUBSCRIPTION_INVOICE_ID=TRUNC(SUBSCRIPTION_INVOICE_ID)),
    CONSTRAINT CK_SI_PERIOD CHECK (period_ends_at_utc>period_starts_at_utc),
    CONSTRAINT CK_SI_DUE_ORDER CHECK (due_at_utc IS NULL OR due_at_utc>=issued_at_utc)
)
