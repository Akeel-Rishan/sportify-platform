CREATE TABLE CUSTOMERS (
    CUSTOMER_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    USER_ID NUMBER,
    FULL_NAME VARCHAR2(160 CHAR) NOT NULL,
    MOBILE_E164 VARCHAR2(16 CHAR) NOT NULL,
    EMAIL VARCHAR2(320 CHAR),
    EMAIL_NORMALIZED VARCHAR2(320 CHAR),
    CUSTOMER_STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    INTERNAL_NOTES VARCHAR2(2000 CHAR),
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    UPDATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT PK_CUSTOMERS PRIMARY KEY (CUSTOMER_ID),
    CONSTRAINT UQ_CUSTOMERS_TENANT_ID UNIQUE (TENANT_ID, CUSTOMER_ID),
    CONSTRAINT UQ_CUSTOMERS_PUBLIC UNIQUE (TENANT_ID, PUBLIC_ID),
    CONSTRAINT CK_CUSTOMERS_EMAIL_PAIR CHECK ((email IS NULL AND email_normalized IS NULL) OR (email IS NOT NULL AND email_normalized IS NOT NULL)),
    CONSTRAINT CK_CUSTOMERS_STATUS CHECK (customer_status IN ('ACTIVE','INACTIVE','BLOCKED')),
    CONSTRAINT CK_CUSTOMERS_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_CUSTOMERS_ID_POSITIVE CHECK (CUSTOMER_ID>0 AND CUSTOMER_ID=TRUNC(CUSTOMER_ID))
)
