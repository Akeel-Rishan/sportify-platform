CREATE TABLE BUSINESS_PAYMENT_SETTINGS (
    BUSINESS_PAYMENT_SETTINGS_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    BUSINESS_ID NUMBER NOT NULL,
    ACCEPT_CASH CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    ACCEPT_BANK_TRANSFER CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    ACCEPT_CARD_AT_VENUE CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    BANK_NAME VARCHAR2(120 CHAR),
    BANK_ACCOUNT_NAME VARCHAR2(160 CHAR),
    BANK_ACCOUNT_NUMBER VARCHAR2(80 CHAR),
    BANK_BRANCH VARCHAR2(120 CHAR),
    TRANSFER_INSTRUCTIONS CLOB,
    UPDATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT PK_BUSINESS_PAYMENT_SETTINGS PRIMARY KEY (BUSINESS_PAYMENT_SETTINGS_ID),
    CONSTRAINT UQ_BPS_BUSINESS UNIQUE (TENANT_ID, BUSINESS_ID),
    CONSTRAINT CK_BUSINESS_PAYMENT_CASH CHECK (accept_cash IN ('Y','N')),
    CONSTRAINT CK_BUSINESS_PAYMENT_BANK CHECK (accept_bank_transfer IN ('Y','N')),
    CONSTRAINT CK_BUSINESS_PAYMENT_CARD CHECK (accept_card_at_venue IN ('Y','N')),
    CONSTRAINT CK_BUSINESS_PAYMENT_SETTINGS_ID_POSITIVE CHECK (BUSINESS_PAYMENT_SETTINGS_ID>0 AND BUSINESS_PAYMENT_SETTINGS_ID=TRUNC(BUSINESS_PAYMENT_SETTINGS_ID))
)
