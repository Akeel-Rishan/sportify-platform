CREATE TABLE STAFF_ASSIGNMENTS (
    STAFF_ASSIGNMENT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    MEMBERSHIP_ID NUMBER NOT NULL,
    LOCATION_ID NUMBER NOT NULL,
    ASSIGNMENT_STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    ASSIGNED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    ENDED_AT_UTC TIMESTAMP(6),
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    CONSTRAINT PK_STAFF_ASSIGNMENTS PRIMARY KEY (STAFF_ASSIGNMENT_ID),
    CONSTRAINT UQ_STAFF_ASSIGNMENTS_TENANT_ID UNIQUE (TENANT_ID, STAFF_ASSIGNMENT_ID),
    CONSTRAINT UQ_STAFF_MEMBER_LOC UNIQUE (TENANT_ID, MEMBERSHIP_ID, LOCATION_ID),
    CONSTRAINT UQ_STAFF_ASSIGNMENTS_PUBLIC_ID UNIQUE (TENANT_ID, PUBLIC_ID),
    CONSTRAINT CK_STAFF_ASSIGNMENTS_STATUS CHECK (assignment_status IN ('ACTIVE','ENDED')),
    CONSTRAINT CK_STAFF_ASSIGNMENTS_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_STAFF_ASSIGNMENTS_ID_POSITIVE CHECK (STAFF_ASSIGNMENT_ID>0 AND STAFF_ASSIGNMENT_ID=TRUNC(STAFF_ASSIGNMENT_ID))
)
