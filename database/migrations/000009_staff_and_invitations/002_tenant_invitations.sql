CREATE TABLE TENANT_INVITATIONS (
    INVITATION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    EMAIL VARCHAR2(320 CHAR) NOT NULL,
    EMAIL_NORMALIZED VARCHAR2(320 CHAR) NOT NULL,
    ROLE_ID NUMBER NOT NULL,
    TOKEN_HASH VARCHAR2(128 CHAR) NOT NULL,
    INVITATION_STATUS VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
    INVITED_BY_MEMBERSHIP_ID NUMBER NOT NULL,
    EXPIRES_AT_UTC TIMESTAMP(6) NOT NULL,
    ACCEPTED_AT_UTC TIMESTAMP(6),
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    TOKEN_KEY_VERSION VARCHAR2(30 CHAR) NOT NULL,
    CONSTRAINT PK_TENANT_INVITATIONS PRIMARY KEY (INVITATION_ID),
    CONSTRAINT UQ_TENANT_INVITATIONS_TOKEN UNIQUE (TOKEN_HASH),
    CONSTRAINT UQ_INV_TENANT_ID UNIQUE (TENANT_ID, INVITATION_ID),
    CONSTRAINT UQ_TENANT_INVITATIONS_PUBLIC_ID UNIQUE (TENANT_ID, PUBLIC_ID),
    CONSTRAINT CK_TENANT_INVITATIONS_STATUS CHECK (invitation_status IN ('PENDING','ACCEPTED','EXPIRED','REVOKED')),
    CONSTRAINT CK_TENANT_INVITATIONS_TOKEN_HASH CHECK (REGEXP_LIKE(TOKEN_HASH,'^[0-9a-f]{64}$','c')),
    CONSTRAINT CK_TENANT_INVITATIONS_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_TENANT_INVITATIONS_ID_POSITIVE CHECK (INVITATION_ID>0 AND INVITATION_ID=TRUNC(INVITATION_ID)),
    CONSTRAINT CK_TENANT_INVITATIONS_EXPIRY CHECK (expires_at_utc>created_at_utc)
)
