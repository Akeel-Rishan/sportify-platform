CREATE TABLE WEBSITE_THEMES (
    THEME_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    THEME_CODE VARCHAR2(50 CHAR) NOT NULL,
    THEME_NAME VARCHAR2(120 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(500 CHAR),
    IS_ACTIVE CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_WEBSITE_THEMES PRIMARY KEY (THEME_ID),
    CONSTRAINT UQ_WEBSITE_THEMES_CODE UNIQUE (THEME_CODE),
    CONSTRAINT CK_WEBSITE_THEMES_ACTIVE CHECK (is_active IN ('Y','N')),
    CONSTRAINT CK_WEBSITE_THEMES_ID_POSITIVE CHECK (THEME_ID>0 AND THEME_ID=TRUNC(THEME_ID))
)
