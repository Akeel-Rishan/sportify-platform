CREATE TABLE WEBSITE_SETTINGS (
    WEBSITE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    BUSINESS_ID NUMBER NOT NULL,
    THEME_ID NUMBER NOT NULL,
    SUBDOMAIN_SLUG VARCHAR2(100 CHAR) NOT NULL,
    WEBSITE_STATUS VARCHAR2(20 CHAR) DEFAULT 'DRAFT' NOT NULL,
    PAGE_TITLE VARCHAR2(180 CHAR),
    META_DESCRIPTION VARCHAR2(500 CHAR),
    PRIMARY_COLOR CHAR(7 CHAR),
    SECONDARY_COLOR CHAR(7 CHAR),
    CANCELLATION_POLICY CLOB,
    TERMS_AND_CONDITIONS CLOB,
    PUBLISHED_AT_UTC TIMESTAMP(6),
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    UPDATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    CONSTRAINT PK_WEBSITE_SETTINGS PRIMARY KEY (WEBSITE_ID),
    CONSTRAINT UQ_WEBSITE_SETTINGS_TENANT_ID UNIQUE (TENANT_ID, WEBSITE_ID),
    CONSTRAINT UQ_WEBSITE_SETTINGS_BUSINESS UNIQUE (TENANT_ID, BUSINESS_ID),
    CONSTRAINT UQ_WEBSITE_SETTINGS_SUBDOMAIN UNIQUE (SUBDOMAIN_SLUG),
    CONSTRAINT UQ_WEBSITE_SETTINGS_PUBLIC_ID UNIQUE (TENANT_ID, PUBLIC_ID),
    CONSTRAINT CK_WEBSITE_SETTINGS_STATUS CHECK (website_status IN ('DRAFT','PUBLISHED','UNPUBLISHED')),
    CONSTRAINT CK_WEBSITE_SETTINGS_SLUG CHECK (REGEXP_LIKE(subdomain_slug,'^[a-z0-9]([a-z0-9-]{0,98}[a-z0-9])?$','c')),
    CONSTRAINT CK_WEBSITE_SETTINGS_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_WEBSITE_SETTINGS_ID_POSITIVE CHECK (WEBSITE_ID>0 AND WEBSITE_ID=TRUNC(WEBSITE_ID)),
    CONSTRAINT CK_WEBSITE_DNS_LABEL CHECK (LENGTH(subdomain_slug)<=63),
    CONSTRAINT CK_WEBSITE_HOST_CANONICAL CHECK (NOT REGEXP_LIKE(subdomain_slug,'[^a-z0-9-]','c') AND subdomain_slug NOT IN ('admin','api','dashboard')),
    CONSTRAINT CK_WEBSITE_PUBLISHED CHECK (website_status<>'PUBLISHED' OR published_at_utc IS NOT NULL)
)
