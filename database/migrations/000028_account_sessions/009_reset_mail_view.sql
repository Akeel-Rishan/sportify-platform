CREATE VIEW VW_AUTH_PASSWORD_RESET_MAIL AS
SELECT t.PUBLIC_ID, t.TOKEN_KEY_VERSION, u.PUBLIC_ID AS USER_PUBLIC_ID, u.EMAIL,
       TO_CHAR(t.EXPIRES_AT_UTC,'YYYY-MM-DD"T"HH24:MI:SS.FF6') AS EXPIRES_AT,
       t.TOKEN_HASH
FROM PASSWORD_RESET_TOKENS t JOIN USERS u ON u.USER_ID=t.USER_ID
WHERE u.ACCOUNT_STATUS='ACTIVE' AND u.EMAIL_VERIFIED_AT_UTC IS NOT NULL AND u.EMAIL IS NOT NULL
  AND EXISTS (SELECT 1 FROM TENANT_USERS m WHERE m.USER_ID=u.USER_ID AND m.MEMBERSHIP_STATUS='ACTIVE')
  AND t.CONSUMED_AT_UTC IS NULL AND t.REVOKED_AT_UTC IS NULL
  AND t.EXPIRES_AT_UTC>SYS_EXTRACT_UTC(SYSTIMESTAMP)
WITH READ ONLY
