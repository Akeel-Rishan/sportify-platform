CREATE TABLE RESOURCE_FEATURES (
    RESOURCE_FEATURE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    RESOURCE_ID NUMBER NOT NULL,
    FEATURE_CODE VARCHAR2(60 CHAR) NOT NULL,
    FEATURE_NAME VARCHAR2(120 CHAR) NOT NULL,
    FEATURE_VALUE VARCHAR2(1000 CHAR),
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT PK_RESOURCE_FEATURES PRIMARY KEY (RESOURCE_FEATURE_ID),
    CONSTRAINT UQ_RESOURCE_FEATURES_TENANT_ID UNIQUE (TENANT_ID, RESOURCE_FEATURE_ID),
    CONSTRAINT UQ_RESOURCE_FEATURES_CODE UNIQUE (TENANT_ID, RESOURCE_ID, FEATURE_CODE),
    CONSTRAINT CK_RESOURCE_FEATURES_ID_POSITIVE CHECK (RESOURCE_FEATURE_ID>0 AND RESOURCE_FEATURE_ID=TRUNC(RESOURCE_FEATURE_ID))
)
