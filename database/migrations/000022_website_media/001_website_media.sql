CREATE TABLE WEBSITE_MEDIA (
    WEBSITE_MEDIA_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    BUSINESS_ID NUMBER NOT NULL,
    LOCATION_ID NUMBER,
    RESOURCE_ID NUMBER,
    OBJECT_KEY VARCHAR2(700 CHAR) NOT NULL,
    ORIGINAL_FILENAME VARCHAR2(255 CHAR),
    CONTENT_TYPE VARCHAR2(100 CHAR) NOT NULL,
    SIZE_BYTES NUMBER(12) NOT NULL,
    MEDIA_KIND VARCHAR2(30 CHAR) NOT NULL,
    ALT_TEXT VARCHAR2(300 CHAR),
    DISPLAY_ORDER NUMBER(5) DEFAULT 0 NOT NULL,
    MEDIA_STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    CONSTRAINT PK_WEBSITE_MEDIA PRIMARY KEY (WEBSITE_MEDIA_ID),
    CONSTRAINT UQ_WEBSITE_MEDIA_TENANT_ID UNIQUE (TENANT_ID, WEBSITE_MEDIA_ID),
    CONSTRAINT UQ_WEBSITE_MEDIA_OBJECT_KEY UNIQUE (OBJECT_KEY),
    CONSTRAINT UQ_WEBSITE_MEDIA_PUBLIC_ID UNIQUE (TENANT_ID, PUBLIC_ID),
    CONSTRAINT CK_WEBSITE_MEDIA_OWNER CHECK (resource_id IS NULL OR location_id IS NOT NULL),
    CONSTRAINT CK_WEBSITE_MEDIA_SIZE CHECK (size_bytes > 0),
    CONSTRAINT CK_WEBSITE_MEDIA_KIND CHECK (media_kind IN ('LOGO','COVER','BUSINESS','LOCATION','RESOURCE','OTHER')),
    CONSTRAINT CK_WEBSITE_MEDIA_STATUS CHECK (media_status IN ('ACTIVE','ARCHIVED','DELETED')),
    CONSTRAINT CK_WEBSITE_MEDIA_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_WEBSITE_MEDIA_ID_POSITIVE CHECK (WEBSITE_MEDIA_ID>0 AND WEBSITE_MEDIA_ID=TRUNC(WEBSITE_MEDIA_ID)),
    CONSTRAINT CK_WEBSITE_OBJECT_KEY CHECK (REGEXP_LIKE(object_key,'^[A-Za-z0-9][A-Za-z0-9/_.-]*$','c') AND NOT REGEXP_LIKE(object_key,'[^A-Za-z0-9/_.-]','c') AND INSTR('/'||object_key||'/','/../')=0 AND INSTR('/'||object_key||'/','/./')=0)
)
