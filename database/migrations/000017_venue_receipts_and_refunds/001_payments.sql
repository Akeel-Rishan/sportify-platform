CREATE TABLE PAYMENTS (
    PAYMENT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    BOOKING_ID NUMBER NOT NULL,
    PAYMENT_METHOD VARCHAR2(30 CHAR) NOT NULL,
    PAYMENT_STATUS VARCHAR2(20 CHAR) DEFAULT 'RECEIVED' NOT NULL,
    AMOUNT NUMBER(12,2) NOT NULL,
    CURRENCY_CODE CHAR(3 CHAR) NOT NULL,
    PAYMENT_REFERENCE VARCHAR2(160 CHAR),
    RECEIVED_AT_UTC TIMESTAMP(6) NOT NULL,
    RECORDED_BY_MEMBERSHIP_ID NUMBER NOT NULL,
    NOTES VARCHAR2(1000 CHAR),
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    VOIDED_AT_UTC TIMESTAMP(6),
    VOID_REASON VARCHAR2(1000 CHAR),
    VOIDED_BY_MEMBERSHIP_ID NUMBER,
    CONSTRAINT PK_PAYMENTS PRIMARY KEY (PAYMENT_ID),
    CONSTRAINT UQ_PAYMENTS_TENANT_ID UNIQUE (TENANT_ID, PAYMENT_ID),
    CONSTRAINT UQ_PAYMENTS_PUBLIC_ID UNIQUE (TENANT_ID, PUBLIC_ID),
    CONSTRAINT UQ_PAYMENT_CURRENCY UNIQUE (TENANT_ID, PAYMENT_ID, CURRENCY_CODE),
    CONSTRAINT CK_PAYMENTS_STATUS CHECK (payment_status IN ('RECEIVED','VOIDED')),
    CONSTRAINT CK_PAYMENTS_AMOUNT CHECK (amount > 0),
    CONSTRAINT CK_PAYMENTS_CURRENCY_CODE CHECK (REGEXP_LIKE(CURRENCY_CODE,'^[A-Z]{3}$','c')),
    CONSTRAINT CK_PAYMENTS_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_PAYMENTS_ID_POSITIVE CHECK (PAYMENT_ID>0 AND PAYMENT_ID=TRUNC(PAYMENT_ID)),
    CONSTRAINT CK_PAYMENTS_VOID CHECK ((payment_status='RECEIVED' AND voided_at_utc IS NULL AND void_reason IS NULL AND VOIDED_BY_MEMBERSHIP_ID IS NULL) OR (payment_status='VOIDED' AND voided_at_utc IS NOT NULL AND void_reason IS NOT NULL AND VOIDED_BY_MEMBERSHIP_ID IS NOT NULL)),
    CONSTRAINT CK_PAYMENTS_METHOD CHECK (payment_method IN ('CASH','BANK_TRANSFER','CARD_AT_VENUE'))
)
