CREATE TABLE REFUNDS (
    REFUND_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    PAYMENT_ID NUMBER NOT NULL,
    AMOUNT NUMBER(12,2) NOT NULL,
    CURRENCY_CODE CHAR(3 CHAR) NOT NULL,
    REFUND_STATUS VARCHAR2(20 CHAR) DEFAULT 'PROCESSED' NOT NULL,
    REFUND_REASON VARCHAR2(1000 CHAR) NOT NULL,
    PROCESSED_AT_UTC TIMESTAMP(6),
    RECORDED_BY_MEMBERSHIP_ID NUMBER NOT NULL,
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    CONSTRAINT PK_REFUNDS PRIMARY KEY (REFUND_ID),
    CONSTRAINT UQ_REFUNDS_TENANT_ID UNIQUE (TENANT_ID, REFUND_ID),
    CONSTRAINT UQ_REFUNDS_PUBLIC_ID UNIQUE (TENANT_ID, PUBLIC_ID),
    CONSTRAINT CK_REFUNDS_AMOUNT CHECK (amount > 0),
    CONSTRAINT CK_REFUNDS_STATUS CHECK (refund_status IN ('REQUESTED','PROCESSED','REJECTED')),
    CONSTRAINT CK_REFUNDS_CURRENCY_CODE CHECK (REGEXP_LIKE(CURRENCY_CODE,'^[A-Z]{3}$','c')),
    CONSTRAINT CK_REFUNDS_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_REFUNDS_ID_POSITIVE CHECK (REFUND_ID>0 AND REFUND_ID=TRUNC(REFUND_ID)),
    CONSTRAINT CK_REFUND_PROCESSED CHECK (refund_status<>'PROCESSED' OR processed_at_utc IS NOT NULL)
)
