CREATE TABLE PRICING_RULES (
    PRICING_RULE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    RESOURCE_ID NUMBER NOT NULL,
    RULE_CODE VARCHAR2(50 CHAR) NOT NULL,
    CURRENCY_CODE CHAR(3 CHAR) DEFAULT 'LKR' NOT NULL,
    HOURLY_RATE NUMBER(12,2) NOT NULL,
    EFFECTIVE_FROM_UTC TIMESTAMP(6) NOT NULL,
    EFFECTIVE_TO_UTC TIMESTAMP(6),
    RULE_STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    UPDATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    CONSTRAINT PK_PRICING_RULES PRIMARY KEY (PRICING_RULE_ID),
    CONSTRAINT UQ_PRICING_RULES_TENANT_ID UNIQUE (TENANT_ID, PRICING_RULE_ID),
    CONSTRAINT UQ_PRICING_RULES_CODE UNIQUE (TENANT_ID, RESOURCE_ID, RULE_CODE),
    CONSTRAINT UQ_PRICING_RULES_PUBLIC_ID UNIQUE (TENANT_ID, PUBLIC_ID),
    CONSTRAINT UQ_PRICE_RESOURCE_KEY UNIQUE (TENANT_ID, RESOURCE_ID, PRICING_RULE_ID),
    CONSTRAINT CK_PRICING_RULES_RATE CHECK (hourly_rate >= 0),
    CONSTRAINT CK_PRICING_RULES_RANGE CHECK (effective_to_utc IS NULL OR effective_to_utc > effective_from_utc),
    CONSTRAINT CK_PRICING_RULES_STATUS CHECK (rule_status IN ('ACTIVE','INACTIVE')),
    CONSTRAINT CK_PRICING_RULES_CURRENCY_CODE CHECK (REGEXP_LIKE(CURRENCY_CODE,'^[A-Z]{3}$','c')),
    CONSTRAINT CK_PRICING_RULES_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_PRICING_RULES_ID_POSITIVE CHECK (PRICING_RULE_ID>0 AND PRICING_RULE_ID=TRUNC(PRICING_RULE_ID))
)
