CREATE TABLE AVAILABILITY_BLOCKS (
    AVAILABILITY_BLOCK_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    LOCATION_ID NUMBER NOT NULL,
    RESOURCE_ID NUMBER,
    STARTS_AT_UTC TIMESTAMP(6) NOT NULL,
    ENDS_AT_UTC TIMESTAMP(6) NOT NULL,
    BLOCK_TYPE VARCHAR2(30 CHAR) NOT NULL,
    REASON VARCHAR2(500 CHAR),
    BLOCK_STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_BY_MEMBERSHIP_ID NUMBER NOT NULL,
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    CONSTRAINT PK_AVAILABILITY_BLOCKS PRIMARY KEY (AVAILABILITY_BLOCK_ID),
    CONSTRAINT UQ_AVAIL_BLK_TENANT_ID UNIQUE (TENANT_ID, AVAILABILITY_BLOCK_ID),
    CONSTRAINT UQ_AVAILABILITY_BLOCKS_PUBLIC_ID UNIQUE (TENANT_ID, PUBLIC_ID),
    CONSTRAINT CK_AVAILABILITY_BLOCKS_RANGE CHECK (ends_at_utc > starts_at_utc),
    CONSTRAINT CK_AVAILABILITY_BLOCKS_TYPE CHECK (block_type IN ('MAINTENANCE','REPAIR','PRIVATE_EVENT','CLEANING','CLOSURE','OTHER')),
    CONSTRAINT CK_AVAILABILITY_BLOCKS_STATUS CHECK (block_status IN ('ACTIVE','CANCELLED')),
    CONSTRAINT CK_AVAILABILITY_BLOCKS_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_AVAILABILITY_BLOCKS_ID_POSITIVE CHECK (AVAILABILITY_BLOCK_ID>0 AND AVAILABILITY_BLOCK_ID=TRUNC(AVAILABILITY_BLOCK_ID))
)
