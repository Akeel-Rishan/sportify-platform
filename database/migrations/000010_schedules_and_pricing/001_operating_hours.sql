CREATE TABLE OPERATING_HOURS (
    OPERATING_HOUR_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    LOCATION_ID NUMBER NOT NULL,
    RESOURCE_ID NUMBER,
    DAY_OF_WEEK NUMBER(1) NOT NULL,
    OPEN_MINUTE NUMBER(4),
    CLOSE_MINUTE NUMBER(4),
    IS_CLOSED CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    SEGMENT_NO NUMBER(3) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_OPERATING_HOURS PRIMARY KEY (OPERATING_HOUR_ID),
    CONSTRAINT UQ_OPERATING_HOURS_TENANT_ID UNIQUE (TENANT_ID, OPERATING_HOUR_ID),
    CONSTRAINT UQ_OPERATING_HOURS_PUBLIC_ID UNIQUE (TENANT_ID, PUBLIC_ID),
    CONSTRAINT UQ_OPERATING_HOURS_SEGMENT UNIQUE (TENANT_ID, LOCATION_ID, RESOURCE_ID, DAY_OF_WEEK, SEGMENT_NO),
    CONSTRAINT CK_OPERATING_HOURS_DAY CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT CK_OPERATING_HOURS_CLOSED CHECK (is_closed IN ('Y','N')),
    CONSTRAINT CK_OPERATING_HOURS_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_OPERATING_HOURS_ID_POSITIVE CHECK (OPERATING_HOUR_ID>0 AND OPERATING_HOUR_ID=TRUNC(OPERATING_HOUR_ID)),
    CONSTRAINT CK_OH_SEGMENT CHECK (segment_no BETWEEN 1 AND 999),
    CONSTRAINT CK_OPERATING_HOURS_TIMES CHECK ((is_closed='Y' AND open_minute IS NULL AND close_minute IS NULL) OR (is_closed='N' AND open_minute IS NOT NULL AND close_minute IS NOT NULL AND open_minute BETWEEN 0 AND 1439 AND close_minute BETWEEN 1 AND 1440 AND close_minute>open_minute AND MOD(open_minute,15)=0 AND MOD(close_minute,15)=0))
)
