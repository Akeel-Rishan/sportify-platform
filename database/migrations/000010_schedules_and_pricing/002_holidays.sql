CREATE TABLE HOLIDAYS (
    HOLIDAY_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    LOCATION_ID NUMBER NOT NULL,
    HOLIDAY_DATE DATE NOT NULL,
    HOLIDAY_NAME VARCHAR2(160 CHAR) NOT NULL,
    IS_CLOSED CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    OPEN_MINUTE NUMBER(4),
    CLOSE_MINUTE NUMBER(4),
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    HOLIDAY_STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT PK_HOLIDAYS PRIMARY KEY (HOLIDAY_ID),
    CONSTRAINT UQ_HOLIDAYS_TENANT_ID UNIQUE (TENANT_ID, HOLIDAY_ID),
    CONSTRAINT UQ_HOLIDAYS_LOCATION_DATE UNIQUE (TENANT_ID, LOCATION_ID, HOLIDAY_DATE),
    CONSTRAINT UQ_HOLIDAYS_PUBLIC_ID UNIQUE (TENANT_ID, PUBLIC_ID),
    CONSTRAINT CK_HOLIDAYS_DATE CHECK (holiday_date = TRUNC(holiday_date)),
    CONSTRAINT CK_HOLIDAYS_CLOSED CHECK (is_closed IN ('Y','N')),
    CONSTRAINT CK_HOLIDAYS_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_HOLIDAYS_ID_POSITIVE CHECK (HOLIDAY_ID>0 AND HOLIDAY_ID=TRUNC(HOLIDAY_ID)),
    CONSTRAINT CK_HOLIDAYS_TIMES CHECK ((is_closed='Y' AND open_minute IS NULL AND close_minute IS NULL) OR (is_closed='N' AND open_minute IS NOT NULL AND close_minute IS NOT NULL AND open_minute BETWEEN 0 AND 1439 AND close_minute BETWEEN 1 AND 1440 AND close_minute>open_minute AND MOD(open_minute,15)=0 AND MOD(close_minute,15)=0)),
    CONSTRAINT CK_HOLIDAY_STATUS CHECK (holiday_status IN ('ACTIVE','INACTIVE'))
)
