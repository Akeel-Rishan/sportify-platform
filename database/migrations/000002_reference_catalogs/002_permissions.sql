CREATE TABLE PERMISSIONS (
  PERMISSION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  PERMISSION_CODE VARCHAR2(100 CHAR) NOT NULL,
  PERMISSION_NAME VARCHAR2(150 CHAR) NOT NULL,
  DESCRIPTION VARCHAR2(500 CHAR),
  CONSTRAINT PK_PERMISSIONS PRIMARY KEY (PERMISSION_ID),
  CONSTRAINT UQ_PERMISSIONS_CODE UNIQUE (PERMISSION_CODE),
  CONSTRAINT CK_PERMISSIONS_ID_POSITIVE CHECK (PERMISSION_ID>0 AND PERMISSION_ID=TRUNC(PERMISSION_ID))
)
