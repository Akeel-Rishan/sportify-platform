CREATE TABLE SPORTS (
  SPORT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  SPORT_CODE VARCHAR2(50 CHAR) NOT NULL,
  SPORT_NAME VARCHAR2(120 CHAR) NOT NULL,
  RESOURCE_LABEL VARCHAR2(80 CHAR),
  IS_ACTIVE CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
  DISPLAY_ORDER NUMBER(5) DEFAULT 0 NOT NULL,
  CONSTRAINT PK_SPORTS PRIMARY KEY (SPORT_ID),
  CONSTRAINT UQ_SPORTS_CODE UNIQUE (SPORT_CODE),
  CONSTRAINT CK_SPORTS_ACTIVE CHECK (is_active IN ('Y','N')),
  CONSTRAINT CK_SPORTS_ID_POSITIVE CHECK (SPORT_ID>0 AND SPORT_ID=TRUNC(SPORT_ID))
)
