CREATE TABLE AUTH_SOURCE_WINDOWS (
    SOURCE_HASH VARCHAR2(64 CHAR) NOT NULL,
    ACTION_SCOPE VARCHAR2(10 CHAR) NOT NULL,
    WINDOW_END_UTC TIMESTAMP(6) NOT NULL,
    REQUEST_COUNT NUMBER(5) NOT NULL,
    CONSTRAINT PK_AUTH_SOURCE_WINDOWS PRIMARY KEY (SOURCE_HASH, ACTION_SCOPE),
    CONSTRAINT CK_AUTH_SOURCE_HASH CHECK (REGEXP_LIKE(SOURCE_HASH,'^[0-9a-f]{64}$','c')),
    CONSTRAINT CK_AUTH_SOURCE_SCOPE CHECK (ACTION_SCOPE IN ('ISSUE','CONFIRM')),
    CONSTRAINT CK_AUTH_SOURCE_COUNT CHECK (REQUEST_COUNT>0)
)
