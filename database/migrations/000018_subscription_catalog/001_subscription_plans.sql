CREATE TABLE SUBSCRIPTION_PLANS (
    PLAN_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    PLAN_CODE VARCHAR2(50 CHAR) NOT NULL,
    PLAN_NAME VARCHAR2(120 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(1000 CHAR),
    PRICE_AMOUNT NUMBER(12,2) NOT NULL,
    CURRENCY_CODE CHAR(3 CHAR) NOT NULL,
    BILLING_INTERVAL VARCHAR2(20 CHAR) NOT NULL,
    TRIAL_DAYS NUMBER(4) NOT NULL,
    IS_ACTIVE CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT PK_SUBSCRIPTION_PLANS PRIMARY KEY (PLAN_ID),
    CONSTRAINT UQ_SUBSCRIPTION_PLANS_CODE UNIQUE (PLAN_CODE),
    CONSTRAINT CK_SUBSCRIPTION_PLANS_PRICE CHECK (price_amount >= 0),
    CONSTRAINT CK_SUBSCRIPTION_PLANS_INTERVAL CHECK (billing_interval IN ('MONTHLY','YEARLY','CUSTOM')),
    CONSTRAINT CK_SUBSCRIPTION_PLANS_TRIAL CHECK (trial_days >= 0),
    CONSTRAINT CK_SUBSCRIPTION_PLANS_ACTIVE CHECK (is_active IN ('Y','N')),
    CONSTRAINT CK_SUBSCRIPTION_PLANS_CURRENCY_CODE CHECK (REGEXP_LIKE(CURRENCY_CODE,'^[A-Z]{3}$','c')),
    CONSTRAINT CK_SUBSCRIPTION_PLANS_ID_POSITIVE CHECK (PLAN_ID>0 AND PLAN_ID=TRUNC(PLAN_ID))
)
