CREATE TABLE SUBSCRIPTION_ENTITLEMENTS (
    PLAN_ID NUMBER NOT NULL,
    FEATURE_CODE VARCHAR2(80 CHAR) NOT NULL,
    IS_ENABLED CHAR(1 CHAR) NOT NULL,
    LIMIT_VALUE NUMBER(12),
    LIMIT_UNIT VARCHAR2(30 CHAR),
    VALUE_KIND VARCHAR2(7 CHAR) NOT NULL,
    CONSTRAINT PK_SUBSCRIPTION_ENTITLEMENTS PRIMARY KEY (PLAN_ID, FEATURE_CODE),
    CONSTRAINT CK_SE_ENABLED CHECK (is_enabled IN ('Y','N')),
    CONSTRAINT CK_SE_LIMIT CHECK (limit_value IS NULL OR limit_value >= 0),
    CONSTRAINT CK_SE_VALUE_KIND CHECK ((value_kind='BOOLEAN' AND limit_value IS NULL AND limit_unit IS NULL) OR (value_kind='LIMIT' AND limit_value IS NOT NULL AND limit_value>=0 AND limit_unit IS NOT NULL AND TRIM(limit_unit) IS NOT NULL))
)
