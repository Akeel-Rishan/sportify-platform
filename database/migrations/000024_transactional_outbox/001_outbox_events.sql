CREATE TABLE OUTBOX_EVENTS (
    OUTBOX_EVENT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER,
    AGGREGATE_TYPE VARCHAR2(80 CHAR) NOT NULL,
    AGGREGATE_ID VARCHAR2(100 CHAR) NOT NULL,
    EVENT_TYPE VARCHAR2(120 CHAR) NOT NULL,
    PAYLOAD CLOB NOT NULL,
    EVENT_STATUS VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
    ATTEMPT_COUNT NUMBER(5) DEFAULT 0 NOT NULL,
    AVAILABLE_AT_UTC TIMESTAMP(6) NOT NULL,
    PROCESSED_AT_UTC TIMESTAMP(6),
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    SCOPE_KIND VARCHAR2(8 CHAR) NOT NULL,
    MAX_ATTEMPTS NUMBER(5) NOT NULL,
    PAYLOAD_VERSION NUMBER(5) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_OUTBOX_EVENTS PRIMARY KEY (OUTBOX_EVENT_ID),
    CONSTRAINT UQ_OUTBOX_SCOPE_ID UNIQUE (SCOPE_KIND, OUTBOX_EVENT_ID),
    CONSTRAINT UQ_OUTBOX_TENANT_ID UNIQUE (TENANT_ID, OUTBOX_EVENT_ID),
    CONSTRAINT CK_OUTBOX_EVENTS_STATUS CHECK (event_status IN ('PENDING','PROCESSING','PROCESSED','FAILED')),
    CONSTRAINT CK_OUTBOX_EVENTS_ID_POSITIVE CHECK (OUTBOX_EVENT_ID>0 AND OUTBOX_EVENT_ID=TRUNC(OUTBOX_EVENT_ID)),
    CONSTRAINT CK_OUTBOX_EVENTS_SCOPE CHECK ((scope_kind='PLATFORM' AND tenant_id IS NULL) OR (scope_kind='TENANT' AND tenant_id IS NOT NULL)),
    CONSTRAINT CK_OUTBOX_ATTEMPTS CHECK (attempt_count>=0 AND max_attempts>0 AND attempt_count<=max_attempts),
    CONSTRAINT CK_OUTBOX_EVENTS_PAYLOAD_VERSION CHECK (payload_version>0),
    CONSTRAINT CK_OUTBOX_PAYLOAD_JSON CHECK (payload IS JSON STRICT WITH UNIQUE KEYS),
    CONSTRAINT CK_OUTBOX_PROCESSED CHECK ((event_status='PROCESSED' AND processed_at_utc IS NOT NULL AND processed_at_utc>=created_at_utc) OR (event_status<>'PROCESSED' AND processed_at_utc IS NULL))
)
