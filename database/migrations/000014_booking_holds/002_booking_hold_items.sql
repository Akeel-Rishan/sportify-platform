CREATE TABLE BOOKING_HOLD_ITEMS (
    HOLD_ITEM_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    HOLD_ID NUMBER NOT NULL,
    BUSINESS_ID NUMBER NOT NULL,
    LOCATION_ID NUMBER NOT NULL,
    RESOURCE_ID NUMBER NOT NULL,
    STARTS_AT_UTC TIMESTAMP(6) NOT NULL,
    ENDS_AT_UTC TIMESTAMP(6) NOT NULL,
    DURATION_MINUTES NUMBER(5) NOT NULL,
    HOURLY_RATE_SNAPSHOT NUMBER(12,2) NOT NULL,
    LINE_TOTAL NUMBER(12,2) NOT NULL,
    CURRENCY_CODE CHAR(3 CHAR) NOT NULL,
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    BUFFER_BEFORE_MINUTES NUMBER(4) NOT NULL,
    BUFFER_AFTER_MINUTES NUMBER(4) NOT NULL,
    OCCUPIED_START_UTC TIMESTAMP(6) NOT NULL,
    OCCUPIED_END_UTC TIMESTAMP(6) NOT NULL,
    PRICING_RULE_ID NUMBER NOT NULL,
    CONSTRAINT PK_BOOKING_HOLD_ITEMS PRIMARY KEY (HOLD_ITEM_ID),
    CONSTRAINT UQ_BHI_TENANT_ID UNIQUE (TENANT_ID, HOLD_ITEM_ID),
    CONSTRAINT UQ_BHI_RESOURCE UNIQUE (TENANT_ID, HOLD_ITEM_ID, RESOURCE_ID),
    CONSTRAINT CK_BOOKING_HOLD_ITEMS_RANGE CHECK (ends_at_utc > starts_at_utc),
    CONSTRAINT CK_BOOKING_HOLD_ITEMS_DURATION CHECK (duration_minutes > 0 AND MOD(duration_minutes,15) = 0 AND (ends_at_utc - starts_at_utc) = NUMTODSINTERVAL(duration_minutes,'MINUTE')),
    CONSTRAINT CK_BOOKING_HOLD_ITEMS_GRID CHECK (MOD(EXTRACT(MINUTE FROM starts_at_utc),15) = 0 AND EXTRACT(SECOND FROM starts_at_utc) = 0),
    CONSTRAINT CK_BOOKING_HOLD_ITEMS_AMOUNTS CHECK (hourly_rate_snapshot >= 0 AND line_total >= 0),
    CONSTRAINT CK_BOOKING_HOLD_ITEMS_CURRENCY_CODE CHECK (REGEXP_LIKE(CURRENCY_CODE,'^[A-Z]{3}$','c')),
    CONSTRAINT CK_BOOKING_HOLD_ITEMS_ID_POSITIVE CHECK (HOLD_ITEM_ID>0 AND HOLD_ITEM_ID=TRUNC(HOLD_ITEM_ID)),
    CONSTRAINT CK_BOOKING_HOLD_ITEMS_OCCUPANCY CHECK (buffer_before_minutes>=0 AND buffer_after_minutes>=0 AND MOD(buffer_before_minutes,15)=0 AND MOD(buffer_after_minutes,15)=0 AND occupied_start_utc=starts_at_utc-NUMTODSINTERVAL(buffer_before_minutes,'MINUTE') AND occupied_end_utc=ends_at_utc+NUMTODSINTERVAL(buffer_after_minutes,'MINUTE'))
)
