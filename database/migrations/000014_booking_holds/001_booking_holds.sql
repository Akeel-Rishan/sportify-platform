CREATE TABLE BOOKING_HOLDS (
    HOLD_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    HOLD_TOKEN_HASH VARCHAR2(128 CHAR) NOT NULL,
    CHECKOUT_SESSION_KEY VARCHAR2(128 CHAR) NOT NULL,
    HOLD_STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    EXPIRES_AT_UTC TIMESTAMP(6) NOT NULL,
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    CONVERTED_AT_UTC TIMESTAMP(6),
    RELEASED_AT_UTC TIMESTAMP(6),
    TOKEN_KEY_VERSION VARCHAR2(30 CHAR) NOT NULL,
    CANCELLATION_POLICY_SNAPSHOT CLOB NOT NULL,
    CONSTRAINT PK_BOOKING_HOLDS PRIMARY KEY (HOLD_ID),
    CONSTRAINT UQ_BOOKING_HOLDS_TENANT_ID UNIQUE (TENANT_ID, HOLD_ID),
    CONSTRAINT UQ_BOOKING_HOLDS_PUBLIC UNIQUE (TENANT_ID, PUBLIC_ID),
    CONSTRAINT UQ_BOOKING_HOLDS_TOKEN UNIQUE (HOLD_TOKEN_HASH),
    CONSTRAINT CK_BOOKING_HOLDS_STATUS CHECK (hold_status IN ('ACTIVE','CONVERTED','EXPIRED','RELEASED')),
    CONSTRAINT CK_BOOKING_HOLDS_EXPIRY CHECK (expires_at_utc > created_at_utc),
    CONSTRAINT CK_BOOKING_HOLDS_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_BOOKING_HOLDS_HOLD_TOKEN_HASH CHECK (REGEXP_LIKE(HOLD_TOKEN_HASH,'^[0-9a-f]{64}$','c')),
    CONSTRAINT CK_BOOKING_HOLDS_ID_POSITIVE CHECK (HOLD_ID>0 AND HOLD_ID=TRUNC(HOLD_ID)),
    CONSTRAINT CK_HOLD_CHECKOUT_DIGEST CHECK (REGEXP_LIKE(checkout_session_key,'^[0-9a-f]{64}$','c'))
)
