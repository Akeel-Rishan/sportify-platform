CREATE TABLE JOB_QUEUE (
    JOB_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER,
    JOB_TYPE VARCHAR2(100 CHAR) NOT NULL,
    PAYLOAD CLOB NOT NULL,
    JOB_STATUS VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
    ATTEMPT_COUNT NUMBER(5) DEFAULT 0 NOT NULL,
    MAX_ATTEMPTS NUMBER(5) NOT NULL,
    RUN_AFTER_UTC TIMESTAMP(6) NOT NULL,
    LOCKED_AT_UTC TIMESTAMP(6),
    LOCKED_BY VARCHAR2(120 CHAR),
    LAST_ERROR VARCHAR2(2000 CHAR),
    DEDUPE_KEY VARCHAR2(160 CHAR),
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    COMPLETED_AT_UTC TIMESTAMP(6),
    SCOPE_KIND VARCHAR2(8 CHAR) NOT NULL,
    PAYLOAD_VERSION NUMBER(5) DEFAULT 1 NOT NULL,
    LEASE_TOKEN VARCHAR2(36 CHAR),
    LEASE_EXPIRES_AT_UTC TIMESTAMP(6),
    SOURCE_OUTBOX_EVENT_ID NUMBER,
    CONSUMER_CODE VARCHAR2(100 CHAR),
    FAILED_AT_UTC TIMESTAMP(6),
    CONSTRAINT PK_JOB_QUEUE PRIMARY KEY (JOB_ID),
    CONSTRAINT UQ_JOB_EVENT_CONSUMER UNIQUE (SOURCE_OUTBOX_EVENT_ID, CONSUMER_CODE),
    CONSTRAINT CK_JOB_QUEUE_STATUS CHECK (job_status IN ('PENDING','RUNNING','COMPLETED','FAILED','CANCELLED')),
    CONSTRAINT CK_JOB_QUEUE_ATTEMPTS CHECK (attempt_count>=0 AND max_attempts>0 AND attempt_count<=max_attempts),
    CONSTRAINT CK_JOB_QUEUE_ID_POSITIVE CHECK (JOB_ID>0 AND JOB_ID=TRUNC(JOB_ID)),
    CONSTRAINT CK_JOB_QUEUE_SCOPE CHECK ((scope_kind='PLATFORM' AND tenant_id IS NULL) OR (scope_kind='TENANT' AND tenant_id IS NOT NULL)),
    CONSTRAINT CK_JOB_QUEUE_PAYLOAD_VERSION CHECK (payload_version>0),
    CONSTRAINT CK_JOB_LEASE CHECK ((job_status='RUNNING' AND lease_token IS NOT NULL AND lease_expires_at_utc IS NOT NULL AND locked_by IS NOT NULL AND locked_at_utc IS NOT NULL AND lease_expires_at_utc>locked_at_utc AND locked_at_utc>=created_at_utc AND attempt_count>0) OR (job_status<>'RUNNING' AND lease_token IS NULL AND lease_expires_at_utc IS NULL AND locked_by IS NULL AND locked_at_utc IS NULL)),
    CONSTRAINT CK_JOB_PAYLOAD_JSON CHECK (payload IS JSON STRICT WITH UNIQUE KEYS),
    CONSTRAINT CK_JOB_SOURCE_PAIR CHECK ((source_outbox_event_id IS NULL AND consumer_code IS NULL) OR (source_outbox_event_id IS NOT NULL AND consumer_code IS NOT NULL AND TRIM(consumer_code) IS NOT NULL)),
    CONSTRAINT CK_JOB_FENCE_UUID CHECK (lease_token IS NULL OR REGEXP_LIKE(lease_token,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_JOB_TERMINAL CHECK ((job_status='COMPLETED' AND completed_at_utc IS NOT NULL AND completed_at_utc>=created_at_utc AND failed_at_utc IS NULL) OR (job_status='FAILED' AND failed_at_utc IS NOT NULL AND failed_at_utc>=created_at_utc AND completed_at_utc IS NULL) OR (job_status IN ('PENDING','RUNNING','CANCELLED') AND completed_at_utc IS NULL AND failed_at_utc IS NULL))
)
