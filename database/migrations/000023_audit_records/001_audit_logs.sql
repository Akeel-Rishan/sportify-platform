CREATE TABLE AUDIT_LOGS (
    AUDIT_LOG_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER,
    ACTOR_USER_ID NUMBER,
    ACTOR_MEMBERSHIP_ID NUMBER,
    ACTION_CODE VARCHAR2(100 CHAR) NOT NULL,
    ENTITY_TYPE VARCHAR2(100 CHAR) NOT NULL,
    ENTITY_PUBLIC_ID VARCHAR2(100 CHAR),
    BEFORE_DATA CLOB,
    AFTER_DATA CLOB,
    REQUEST_ID VARCHAR2(100 CHAR),
    IP_ADDRESS VARCHAR2(45 CHAR),
    USER_AGENT VARCHAR2(1000 CHAR),
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    SCOPE_KIND VARCHAR2(8 CHAR) NOT NULL,
    ACTOR_TYPE VARCHAR2(20 CHAR) NOT NULL,
    ACTOR_PLATFORM_ADMIN_ID NUMBER,
    ACTOR_SERVICE VARCHAR2(80 CHAR),
    ACTOR_KEY VARCHAR2(128 CHAR),
    PAYLOAD_VERSION NUMBER(5) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_AUDIT_LOGS PRIMARY KEY (AUDIT_LOG_ID),
    CONSTRAINT UQ_AUDIT_LOGS_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT CK_AUDIT_LOGS_MEMBERSHIP CHECK (actor_membership_id IS NULL OR (tenant_id IS NOT NULL AND actor_user_id IS NOT NULL)),
    CONSTRAINT CK_AUDIT_LOGS_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_AUDIT_LOGS_ID_POSITIVE CHECK (AUDIT_LOG_ID>0 AND AUDIT_LOG_ID=TRUNC(AUDIT_LOG_ID)),
    CONSTRAINT CK_AUDIT_LOGS_SCOPE CHECK ((scope_kind='PLATFORM' AND tenant_id IS NULL) OR (scope_kind='TENANT' AND tenant_id IS NOT NULL)),
    CONSTRAINT CK_AUDIT_ACTOR CHECK ((actor_type='USER' AND actor_user_id IS NOT NULL AND actor_platform_admin_id IS NULL AND actor_service IS NULL AND actor_key IS NULL AND ((tenant_id IS NULL AND actor_membership_id IS NULL) OR (tenant_id IS NOT NULL AND actor_membership_id IS NOT NULL))) OR (actor_type='PLATFORM_ADMIN' AND actor_platform_admin_id IS NOT NULL AND actor_user_id IS NOT NULL AND actor_membership_id IS NULL AND actor_service IS NULL AND actor_key IS NULL) OR (actor_type IN ('WORKER','SYSTEM') AND actor_service IS NOT NULL AND actor_user_id IS NULL AND actor_membership_id IS NULL AND actor_platform_admin_id IS NULL AND actor_key IS NULL) OR (actor_type='GUEST' AND tenant_id IS NOT NULL AND actor_key IS NOT NULL AND actor_user_id IS NULL AND actor_membership_id IS NULL AND actor_platform_admin_id IS NULL AND actor_service IS NULL)),
    CONSTRAINT CK_AUDIT_BEFORE_DATA_JSON CHECK (BEFORE_DATA IS JSON STRICT WITH UNIQUE KEYS),
    CONSTRAINT CK_AUDIT_AFTER_DATA_JSON CHECK (AFTER_DATA IS JSON STRICT WITH UNIQUE KEYS),
    CONSTRAINT CK_AUDIT_PAYLOAD_VERSION CHECK (payload_version>0)
)
