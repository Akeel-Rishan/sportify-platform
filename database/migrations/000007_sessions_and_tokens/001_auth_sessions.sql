CREATE TABLE AUTH_SESSIONS (
    SESSION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    USER_ID NUMBER NOT NULL,
    TOKEN_HASH VARCHAR2(128 CHAR) NOT NULL,
    EXPIRES_AT_UTC TIMESTAMP(6) NOT NULL,
    REVOKED_AT_UTC TIMESTAMP(6),
    LAST_SEEN_AT_UTC TIMESTAMP(6),
    IP_ADDRESS VARCHAR2(45 CHAR),
    USER_AGENT VARCHAR2(1000 CHAR),
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    AUDIENCE VARCHAR2(20 CHAR) NOT NULL,
    ACTIVE_TENANT_ID NUMBER,
    ACTIVE_MEMBERSHIP_ID NUMBER,
    CONSTRAINT PK_AUTH_SESSIONS PRIMARY KEY (SESSION_ID),
    CONSTRAINT UQ_AUTH_SESSIONS_TOKEN UNIQUE (TOKEN_HASH),
    CONSTRAINT CK_AUTH_SESSIONS_EXPIRY CHECK (expires_at_utc > created_at_utc),
    CONSTRAINT CK_AUTH_SESSIONS_TOKEN_HASH CHECK (REGEXP_LIKE(TOKEN_HASH,'^[0-9a-f]{64}$','c')),
    CONSTRAINT CK_AUTH_SESSIONS_ID_POSITIVE CHECK (SESSION_ID>0 AND SESSION_ID=TRUNC(SESSION_ID)),
    CONSTRAINT CK_SESSION_AUDIENCE CHECK (audience IN ('DASHBOARD','ADMIN')),
    CONSTRAINT CK_SESSION_MEMBER_PAIR CHECK ((active_tenant_id IS NULL AND active_membership_id IS NULL) OR (audience='DASHBOARD' AND active_tenant_id IS NOT NULL AND active_membership_id IS NOT NULL))
)
