CREATE TABLE EMAIL_VERIFICATION_TOKENS (
    VERIFICATION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    USER_ID NUMBER NOT NULL,
    TOKEN_HASH VARCHAR2(128 CHAR) NOT NULL,
    EXPIRES_AT_UTC TIMESTAMP(6) NOT NULL,
    CONSUMED_AT_UTC TIMESTAMP(6),
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    TOKEN_KEY_VERSION VARCHAR2(30 CHAR) NOT NULL,
    REVOKED_AT_UTC TIMESTAMP(6),
    CONSTRAINT PK_EMAIL_VERIFICATION_TOKENS PRIMARY KEY (VERIFICATION_ID),
    CONSTRAINT UQ_EMAIL_VERIFICATION_TOKEN UNIQUE (TOKEN_HASH),
    CONSTRAINT UQ_EMAIL_VERIFICATION_TOKENS_PUBLIC UNIQUE (PUBLIC_ID),
    CONSTRAINT CK_EMAIL_VERIFICATION_TOKENS_TOKEN_HASH CHECK (REGEXP_LIKE(TOKEN_HASH,'^[0-9a-f]{64}$','c')),
    CONSTRAINT CK_EMAIL_VERIFICATION_TOKENS_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_EMAIL_VERIFICATION_TOKENS_ID_POSITIVE CHECK (VERIFICATION_ID>0 AND VERIFICATION_ID=TRUNC(VERIFICATION_ID)),
    CONSTRAINT CK_EMAIL_VERIFICATION_TOKENS_EXPIRY CHECK (expires_at_utc>created_at_utc)
)
