CREATE TABLE TENANTS (
    TENANT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    TENANT_CODE VARCHAR2(60 CHAR) NOT NULL,
    TENANT_NAME VARCHAR2(200 CHAR) NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'TRIAL' NOT NULL,
    DEFAULT_CURRENCY CHAR(3 CHAR) DEFAULT 'LKR' NOT NULL,
    TIMEZONE_NAME VARCHAR2(64 CHAR) DEFAULT 'Asia/Colombo' NOT NULL,
    DEFAULT_LANGUAGE VARCHAR2(10 CHAR) DEFAULT 'en' NOT NULL,
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    UPDATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    DELETED_AT_UTC TIMESTAMP(6),
    CONSTRAINT PK_TENANTS PRIMARY KEY (TENANT_ID),
    CONSTRAINT UQ_TENANTS_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT UQ_TENANTS_CODE UNIQUE (TENANT_CODE),
    CONSTRAINT CK_TENANTS_STATUS CHECK (status IN ('TRIAL','ACTIVE','SUSPENDED','CLOSED')),
    CONSTRAINT CK_TENANTS_CURRENCY CHECK (REGEXP_LIKE(default_currency, '^[A-Z]{3}$')),
    CONSTRAINT CK_TENANTS_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_TENANTS_DEFAULT_CURRENCY CHECK (REGEXP_LIKE(DEFAULT_CURRENCY,'^[A-Z]{3}$','c')),
    CONSTRAINT CK_TENANTS_ID_POSITIVE CHECK (TENANT_ID>0 AND TENANT_ID=TRUNC(TENANT_ID))
)
