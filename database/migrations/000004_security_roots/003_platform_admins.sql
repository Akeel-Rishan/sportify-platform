CREATE TABLE PLATFORM_ADMINS (
    PLATFORM_ADMIN_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    USER_ID NUMBER NOT NULL,
    ADMIN_ROLE_CODE VARCHAR2(40 CHAR) NOT NULL,
    ADMIN_STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT PK_PLATFORM_ADMINS PRIMARY KEY (PLATFORM_ADMIN_ID),
    CONSTRAINT UQ_PLATFORM_ADMINS_USER UNIQUE (USER_ID),
    CONSTRAINT UQ_ADMIN_USER_PAIR UNIQUE (PLATFORM_ADMIN_ID, USER_ID),
    CONSTRAINT CK_PLATFORM_ADMINS_ROLE CHECK (admin_role_code IN ('SUPER_ADMIN','PLATFORM_ADMIN','SUPPORT_AGENT')),
    CONSTRAINT CK_PLATFORM_ADMINS_STATUS CHECK (admin_status IN ('ACTIVE','DISABLED')),
    CONSTRAINT CK_PLATFORM_ADMINS_ID_POSITIVE CHECK (PLATFORM_ADMIN_ID>0 AND PLATFORM_ADMIN_ID=TRUNC(PLATFORM_ADMIN_ID))
)
