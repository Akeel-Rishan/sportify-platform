CREATE TABLE USERS (
    USER_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    FULL_NAME VARCHAR2(160 CHAR) NOT NULL,
    EMAIL VARCHAR2(320 CHAR),
    EMAIL_NORMALIZED VARCHAR2(320 CHAR),
    MOBILE_E164 VARCHAR2(16 CHAR),
    PASSWORD_HASH VARCHAR2(500 CHAR) NOT NULL,
    ACCOUNT_STATUS VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
    EMAIL_VERIFIED_AT_UTC TIMESTAMP(6),
    PHONE_VERIFIED_AT_UTC TIMESTAMP(6),
    LAST_LOGIN_AT_UTC TIMESTAMP(6),
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    UPDATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_USERS_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT UQ_USERS_EMAIL_NORMALIZED UNIQUE (EMAIL_NORMALIZED),
    CONSTRAINT CK_USERS_STATUS CHECK (account_status IN ('PENDING','ACTIVE','LOCKED','DISABLED')),
    CONSTRAINT CK_USERS_EMAIL_PAIR CHECK ((email IS NULL AND email_normalized IS NULL) OR (email IS NOT NULL AND email_normalized IS NOT NULL)),
    CONSTRAINT CK_USERS_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_USERS_ID_POSITIVE CHECK (USER_ID>0 AND USER_ID=TRUNC(USER_ID))
)
