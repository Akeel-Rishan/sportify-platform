CREATE TABLE SUBSCRIPTION_FEATURE_SNAPSHOTS (
    TENANT_ID NUMBER NOT NULL,
    SUBSCRIPTION_ID NUMBER NOT NULL,
    FEATURE_CODE VARCHAR2(80 CHAR) NOT NULL,
    IS_ENABLED CHAR(1 CHAR) NOT NULL,
    LIMIT_VALUE NUMBER(12),
    LIMIT_UNIT VARCHAR2(30 CHAR),
    VALUE_KIND VARCHAR2(7 CHAR) NOT NULL,
    CONSTRAINT PK_SUB_FEATURE_SNAPSHOTS PRIMARY KEY (TENANT_ID, SUBSCRIPTION_ID, FEATURE_CODE),
    CONSTRAINT CK_SFS_VALUES CHECK (is_enabled IN ('Y','N') AND (limit_value IS NULL OR limit_value>=0)),
    CONSTRAINT CK_SFS_VALUE_KIND CHECK ((value_kind='BOOLEAN' AND limit_value IS NULL AND limit_unit IS NULL) OR (value_kind='LIMIT' AND limit_value IS NOT NULL AND limit_value>=0 AND limit_unit IS NOT NULL AND TRIM(limit_unit) IS NOT NULL))
)
