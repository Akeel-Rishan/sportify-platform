CREATE TABLE SUBSCRIPTIONS (
    SUBSCRIPTION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    PLAN_ID NUMBER NOT NULL,
    SUBSCRIPTION_STATUS VARCHAR2(20 CHAR) DEFAULT 'TRIAL' NOT NULL,
    STARTS_AT_UTC TIMESTAMP(6) NOT NULL,
    ENDS_AT_UTC TIMESTAMP(6) NOT NULL,
    TRIAL_STARTS_AT_UTC TIMESTAMP(6),
    TRIAL_ENDS_AT_UTC TIMESTAMP(6),
    GRACE_ENDS_AT_UTC TIMESTAMP(6),
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    UPDATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    PLAN_NAME_SNAPSHOT VARCHAR2(120 CHAR) NOT NULL,
    PRICE_AMOUNT_SNAPSHOT NUMBER(12,2) NOT NULL,
    CURRENCY_CODE CHAR(3 CHAR) NOT NULL,
    BILLING_INTERVAL_SNAPSHOT VARCHAR2(20 CHAR) NOT NULL,
    CONSTRAINT PK_SUBSCRIPTIONS PRIMARY KEY (SUBSCRIPTION_ID),
    CONSTRAINT UQ_SUBSCRIPTIONS_TENANT_ID UNIQUE (TENANT_ID, SUBSCRIPTION_ID),
    CONSTRAINT UQ_SUBSCRIPTION_CURRENCY UNIQUE (TENANT_ID, SUBSCRIPTION_ID, CURRENCY_CODE),
    CONSTRAINT CK_SUBSCRIPTIONS_PERIOD CHECK (ends_at_utc IS NULL OR ends_at_utc > starts_at_utc),
    CONSTRAINT CK_SUBSCRIPTIONS_TRIAL CHECK (trial_ends_at_utc IS NULL OR trial_starts_at_utc IS NULL OR trial_ends_at_utc >= trial_starts_at_utc),
    CONSTRAINT CK_SUBSCRIPTIONS_ID_POSITIVE CHECK (SUBSCRIPTION_ID>0 AND SUBSCRIPTION_ID=TRUNC(SUBSCRIPTION_ID)),
    CONSTRAINT CK_SUBSCRIPTION_SNAPSHOT CHECK (price_amount_snapshot>=0 AND REGEXP_LIKE(currency_code,'^[A-Z]{3}$','c') AND billing_interval_snapshot IN ('MONTHLY','YEARLY','CUSTOM')),
    CONSTRAINT CK_SUBSCRIPTIONS_STATUS CHECK (subscription_status IN ('SCHEDULED','TRIAL','ACTIVE','PAST_DUE','GRACE','SUSPENDED','CANCELLED','EXPIRED')),
    CONSTRAINT CK_SUBSCRIPTION_TRIAL_PAIR CHECK ((trial_starts_at_utc IS NULL AND trial_ends_at_utc IS NULL) OR (trial_starts_at_utc IS NOT NULL AND trial_ends_at_utc IS NOT NULL AND trial_ends_at_utc>trial_starts_at_utc)),
    CONSTRAINT CK_SUBSCRIPTION_TRIAL_STATE CHECK (subscription_status<>'TRIAL' OR (trial_starts_at_utc IS NOT NULL AND trial_ends_at_utc IS NOT NULL)),
    CONSTRAINT CK_SUBSCRIPTION_GRACE CHECK (subscription_status<>'GRACE' OR (grace_ends_at_utc IS NOT NULL AND grace_ends_at_utc>=ends_at_utc)),
    CONSTRAINT CK_SUB_TRIAL_WITHIN_TERM CHECK (trial_starts_at_utc IS NULL OR (trial_starts_at_utc>=starts_at_utc AND trial_ends_at_utc<=ends_at_utc))
)
