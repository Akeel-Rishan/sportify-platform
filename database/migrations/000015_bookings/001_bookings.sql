CREATE TABLE BOOKINGS (
    BOOKING_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    BOOKING_REFERENCE VARCHAR2(40 CHAR) NOT NULL,
    BUSINESS_ID NUMBER NOT NULL,
    CUSTOMER_ID NUMBER NOT NULL,
    SOURCE_HOLD_ID NUMBER,
    BOOKING_STATUS VARCHAR2(20 CHAR) DEFAULT 'CONFIRMED' NOT NULL,
    PAYMENT_STATUS VARCHAR2(20 CHAR) DEFAULT 'UNPAID' NOT NULL,
    BOOKING_SOURCE VARCHAR2(20 CHAR) NOT NULL,
    CURRENCY_CODE CHAR(3 CHAR) NOT NULL,
    TOTAL_AMOUNT NUMBER(12,2) NOT NULL,
    CUSTOMER_NAME_SNAPSHOT VARCHAR2(160 CHAR) NOT NULL,
    CUSTOMER_MOBILE_SNAPSHOT VARCHAR2(16 CHAR) NOT NULL,
    CUSTOMER_EMAIL_SNAPSHOT VARCHAR2(320 CHAR),
    BOOKING_NOTES VARCHAR2(2000 CHAR),
    CREATED_BY_MEMBERSHIP_ID NUMBER,
    CONFIRMED_AT_UTC TIMESTAMP(6),
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    UPDATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    CANCELLATION_POLICY_SNAPSHOT CLOB NOT NULL,
    PAYMENT_PREFERENCE VARCHAR2(20 CHAR),
    CONSTRAINT PK_BOOKINGS PRIMARY KEY (BOOKING_ID),
    CONSTRAINT UQ_BOOKINGS_TENANT_ID UNIQUE (TENANT_ID, BOOKING_ID),
    CONSTRAINT UQ_BOOKINGS_REFERENCE UNIQUE (TENANT_ID, BOOKING_REFERENCE),
    CONSTRAINT UQ_BOOKINGS_BUSINESS_KEY UNIQUE (TENANT_ID, BOOKING_ID, BUSINESS_ID),
    CONSTRAINT UQ_BOOKINGS_CUSTOMER_KEY UNIQUE (TENANT_ID, BOOKING_ID, CUSTOMER_ID),
    CONSTRAINT UQ_BOOKINGS_PUBLIC UNIQUE (TENANT_ID, PUBLIC_ID),
    CONSTRAINT UQ_BOOKING_CURRENCY UNIQUE (TENANT_ID, BOOKING_ID, CURRENCY_CODE),
    CONSTRAINT CK_BOOKINGS_STATUS CHECK (booking_status IN ('PENDING_PAYMENT','CONFIRMED','CANCELLED','COMPLETED','NO_SHOW')),
    CONSTRAINT CK_BOOKINGS_PAYMENT_STATUS CHECK (payment_status IN ('UNPAID','PARTIALLY_PAID','PAID','PARTIALLY_REFUNDED','REFUNDED')),
    CONSTRAINT CK_BOOKINGS_SOURCE CHECK (booking_source IN ('ONLINE','WALK_IN','PHONE','WHATSAPP','STAFF')),
    CONSTRAINT CK_BOOKINGS_TOTAL CHECK (total_amount >= 0),
    CONSTRAINT CK_BOOKINGS_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_BOOKINGS_CURRENCY_CODE CHECK (REGEXP_LIKE(CURRENCY_CODE,'^[A-Z]{3}$','c')),
    CONSTRAINT CK_BOOKINGS_ID_POSITIVE CHECK (BOOKING_ID>0 AND BOOKING_ID=TRUNC(BOOKING_ID)),
    CONSTRAINT CK_BOOKING_PREFERENCE CHECK (payment_preference IS NULL OR payment_preference IN ('CASH_AT_VENUE','BANK_TRANSFER','CARD_AT_VENUE')),
    CONSTRAINT CK_ONLINE_PREFERENCE CHECK (booking_source<>'ONLINE' OR payment_preference IS NOT NULL),
    CONSTRAINT CK_BOOKINGS_ZERO_PAYMENT CHECK (total_amount <> 0 OR payment_status = 'PAID')
)
