CREATE TABLE TENANT_USERS (
    MEMBERSHIP_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    USER_ID NUMBER NOT NULL,
    MEMBERSHIP_STATUS VARCHAR2(20 CHAR) DEFAULT 'INVITED' NOT NULL,
    INVITED_BY_MEMBERSHIP_ID NUMBER,
    JOINED_AT_UTC TIMESTAMP(6),
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    UPDATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    CONSTRAINT PK_TENANT_USERS PRIMARY KEY (MEMBERSHIP_ID),
    CONSTRAINT UQ_TU_TENANT_MEMBER UNIQUE (TENANT_ID, MEMBERSHIP_ID),
    CONSTRAINT UQ_TU_TENANT_MEMBER_USER UNIQUE (TENANT_ID, MEMBERSHIP_ID, USER_ID),
    CONSTRAINT UQ_TENANT_USERS_TENANT_USER UNIQUE (TENANT_ID, USER_ID),
    CONSTRAINT UQ_TENANT_USERS_PUBLIC_ID UNIQUE (TENANT_ID, PUBLIC_ID),
    CONSTRAINT CK_TENANT_USERS_STATUS CHECK (membership_status IN ('INVITED','ACTIVE','SUSPENDED','REVOKED')),
    CONSTRAINT CK_TENANT_USERS_UUID CHECK (REGEXP_LIKE(public_id,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_TENANT_USERS_ID_POSITIVE CHECK (MEMBERSHIP_ID>0 AND MEMBERSHIP_ID=TRUNC(MEMBERSHIP_ID))
)
