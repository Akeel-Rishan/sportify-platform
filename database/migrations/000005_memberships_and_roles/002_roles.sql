CREATE TABLE ROLES (
    ROLE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    ROLE_CODE VARCHAR2(50 CHAR) NOT NULL,
    ROLE_NAME VARCHAR2(100 CHAR) NOT NULL,
    IS_SYSTEM_ROLE CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    IS_ACTIVE CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT PK_ROLES PRIMARY KEY (ROLE_ID),
    CONSTRAINT UQ_ROLES_TENANT_ROLE UNIQUE (TENANT_ID, ROLE_ID),
    CONSTRAINT UQ_ROLES_TENANT_CODE UNIQUE (TENANT_ID, ROLE_CODE),
    CONSTRAINT UQ_ROLES_TENANT_NAME UNIQUE (TENANT_ID, ROLE_NAME),
    CONSTRAINT CK_ROLES_SYSTEM CHECK (is_system_role IN ('Y','N')),
    CONSTRAINT CK_ROLES_ACTIVE CHECK (is_active IN ('Y','N')),
    CONSTRAINT CK_ROLES_ID_POSITIVE CHECK (ROLE_ID>0 AND ROLE_ID=TRUNC(ROLE_ID))
)
