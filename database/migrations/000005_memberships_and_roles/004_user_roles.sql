CREATE TABLE USER_ROLES (
    TENANT_ID NUMBER NOT NULL,
    MEMBERSHIP_ID NUMBER NOT NULL,
    ROLE_ID NUMBER NOT NULL,
    ASSIGNED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    ASSIGNED_BY_MEMBERSHIP_ID NUMBER,
    CONSTRAINT PK_USER_ROLES PRIMARY KEY (TENANT_ID, MEMBERSHIP_ID, ROLE_ID)
)
