CREATE TABLE SCHEMA_MIGRATIONS (
  VERSION VARCHAR2(50 CHAR) NOT NULL,
  DESCRIPTION VARCHAR2(250 CHAR) NOT NULL,
  CHECKSUM VARCHAR2(64 CHAR) NOT NULL,
  INSTALLED_AT_UTC TIMESTAMP(6),
  INSTALLED_BY VARCHAR2(128 CHAR) DEFAULT USER NOT NULL,
  STARTED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
  FINISHED_AT_UTC TIMESTAMP(6),
  EXECUTION_STATUS VARCHAR2(12 CHAR) DEFAULT 'RUNNING' NOT NULL,
  RUNNER_ID VARCHAR2(36 CHAR) NOT NULL,
  EXECUTION_MS NUMBER(12),
  ATTEMPT_COUNT NUMBER(5) DEFAULT 1 NOT NULL,
  ERROR_CODE VARCHAR2(80 CHAR),
  REPAIR_VERSION VARCHAR2(50 CHAR),
  CONSTRAINT PK_SCHEMA_MIGRATIONS PRIMARY KEY (VERSION),
  CONSTRAINT CK_MIGRATION_RECORD CHECK (execution_status IN ('RUNNING','APPLIED','FAILED') AND attempt_count>0 AND REGEXP_LIKE(checksum,'^[0-9a-f]{64}$','c') AND (repair_version IS NULL OR (execution_status='FAILED' AND repair_version<>version))),
  CONSTRAINT CK_MIGRATION_TIMES CHECK ((execution_status='RUNNING' AND installed_at_utc IS NULL AND finished_at_utc IS NULL AND execution_ms IS NULL) OR (execution_status='APPLIED' AND installed_at_utc IS NOT NULL AND finished_at_utc IS NOT NULL AND execution_ms IS NOT NULL AND execution_ms>=0 AND error_code IS NULL) OR (execution_status='FAILED' AND installed_at_utc IS NULL AND finished_at_utc IS NOT NULL AND execution_ms IS NOT NULL AND execution_ms>=0 AND error_code IS NOT NULL))
)
