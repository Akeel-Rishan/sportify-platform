CREATE TABLE IDEMPOTENCY_KEYS (
    IDEMPOTENCY_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER,
    OPERATION_SCOPE VARCHAR2(100 CHAR) NOT NULL,
    IDEMPOTENCY_KEY VARCHAR2(160 CHAR) NOT NULL,
    REQUEST_HASH VARCHAR2(128 CHAR) NOT NULL,
    RESPONSE_STATUS NUMBER(3),
    RESPONSE_BODY CLOB,
    EXPIRES_AT_UTC TIMESTAMP(6) NOT NULL,
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    OWNER_SCOPE VARCHAR2(64 CHAR) NOT NULL,
    OWNER_TYPE VARCHAR2(20 CHAR) NOT NULL,
    EXECUTION_STATUS VARCHAR2(20 CHAR) DEFAULT 'PROCESSING' NOT NULL,
    LEASE_TOKEN VARCHAR2(36 CHAR),
    LEASE_EXPIRES_AT_UTC TIMESTAMP(6),
    SCOPE_KIND VARCHAR2(8 CHAR) NOT NULL,
    RESPONSE_VERSION NUMBER(5) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_IDEMPOTENCY_KEYS PRIMARY KEY (IDEMPOTENCY_ID),
    CONSTRAINT UQ_IDEMPOTENCY_OWNER_KEY UNIQUE (SCOPE_KIND, TENANT_ID, OPERATION_SCOPE, OWNER_TYPE, OWNER_SCOPE, IDEMPOTENCY_KEY),
    CONSTRAINT CK_IDEMPOTENCY_KEYS_REQUEST_HASH CHECK (REGEXP_LIKE(REQUEST_HASH,'^[0-9a-f]{64}$','c')),
    CONSTRAINT CK_IDEMPOTENCY_KEYS_ID_POSITIVE CHECK (IDEMPOTENCY_ID>0 AND IDEMPOTENCY_ID=TRUNC(IDEMPOTENCY_ID)),
    CONSTRAINT CK_IDEM_STATE CHECK (owner_type IN ('USER','GUEST') AND execution_status IN ('PROCESSING','COMPLETED','FAILED') AND expires_at_utc>created_at_utc AND REGEXP_LIKE(owner_scope,'^[0-9a-f]{64}$','c')),
    CONSTRAINT CK_IDEM_LEASE CHECK ((execution_status='PROCESSING' AND lease_token IS NOT NULL AND lease_expires_at_utc IS NOT NULL AND lease_expires_at_utc>created_at_utc AND lease_expires_at_utc<=expires_at_utc) OR (execution_status<>'PROCESSING' AND lease_token IS NULL AND lease_expires_at_utc IS NULL)),
    CONSTRAINT CK_IDEM_HTTP_STATUS CHECK (response_status IS NULL OR response_status BETWEEN 100 AND 599),
    CONSTRAINT CK_IDEM_SCOPE CHECK ((scope_kind='PLATFORM' AND tenant_id IS NULL) OR (scope_kind='TENANT' AND tenant_id IS NOT NULL)),
    CONSTRAINT CK_IDEM_RESPONSE_JSON CHECK (response_body IS JSON STRICT WITH UNIQUE KEYS),
    CONSTRAINT CK_IDEM_RESPONSE_VERSION CHECK (response_version>0),
    CONSTRAINT CK_IDEM_KEY_LENGTH CHECK (LENGTH(idempotency_key) BETWEEN 8 AND 160),
    CONSTRAINT CK_IDEM_FENCE_UUID CHECK (lease_token IS NULL OR REGEXP_LIKE(lease_token,'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$','c')),
    CONSTRAINT CK_IDEM_RESULT_STATE CHECK ((execution_status='PROCESSING' AND response_status IS NULL AND response_body IS NULL) OR (execution_status='COMPLETED' AND response_status IS NOT NULL AND response_status BETWEEN 200 AND 599) OR (execution_status='FAILED' AND (response_status IS NULL OR response_status BETWEEN 400 AND 599)))
)
