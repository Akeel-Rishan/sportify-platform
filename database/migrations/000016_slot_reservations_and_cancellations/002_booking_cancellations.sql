CREATE TABLE BOOKING_CANCELLATIONS (
    CANCELLATION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TENANT_ID NUMBER NOT NULL,
    BOOKING_ID NUMBER NOT NULL,
    CANCELLED_BY_MEMBERSHIP_ID NUMBER NOT NULL,
    CANCELLATION_REASON VARCHAR2(1000 CHAR) NOT NULL,
    CANCELLATION_SOURCE VARCHAR2(20 CHAR) DEFAULT 'STAFF' NOT NULL,
    CANCELLED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT PK_BOOKING_CANCELLATIONS PRIMARY KEY (CANCELLATION_ID),
    CONSTRAINT UQ_BC_TENANT_ID UNIQUE (TENANT_ID, CANCELLATION_ID),
    CONSTRAINT UQ_BC_BOOKING UNIQUE (TENANT_ID, BOOKING_ID),
    CONSTRAINT CK_BC_SOURCE CHECK (cancellation_source IN ('STAFF','ADMIN','SYSTEM')),
    CONSTRAINT CK_BOOKING_CANCELLATIONS_ID_POSITIVE CHECK (CANCELLATION_ID>0 AND CANCELLATION_ID=TRUNC(CANCELLATION_ID))
)
