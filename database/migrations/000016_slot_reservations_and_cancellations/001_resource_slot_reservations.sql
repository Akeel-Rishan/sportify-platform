CREATE TABLE RESOURCE_SLOT_RESERVATIONS (
    TENANT_ID NUMBER NOT NULL,
    RESOURCE_ID NUMBER NOT NULL,
    SLOT_START_UTC TIMESTAMP(6) NOT NULL,
    BOOKING_ITEM_ID NUMBER,
    HOLD_ITEM_ID NUMBER,
    CREATED_AT_UTC TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT PK_RESOURCE_SLOT_RESERVATIONS PRIMARY KEY (TENANT_ID, RESOURCE_ID, SLOT_START_UTC),
    CONSTRAINT CK_SLOT_RESERVATIONS_OWNER CHECK ((booking_item_id IS NOT NULL AND hold_item_id IS NULL) OR (booking_item_id IS NULL AND hold_item_id IS NOT NULL)),
    CONSTRAINT CK_SLOT_RESERVATIONS_GRID CHECK (MOD(EXTRACT(MINUTE FROM slot_start_utc),15) = 0 AND EXTRACT(SECOND FROM slot_start_utc) = 0)
)
