// Explicit disposable Step 07 suite. Never imported by application bootstrap.
// No API/worker startup or pull-request CI imports this file.
import { randomUUID } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { EnvironmentError } from '@sportify/validation';
import { verifyFailureRecovery } from './support/failure-recovery.mjs';
import { verifyIntegrity } from './support/integrity.mjs';
import { verifySeedRepeat } from './support/seed-repeat.mjs';
import { reconcileExtendedStorageFailure } from './support/extended-storage-recovery.mjs';
import {
  runtimeVerificationConfigs,
  verifyRuntimePrivileges,
} from './support/runtime-privileges.mjs';
import {
  loadManifest,
  parseMigrationConfig,
  assertReady,
  withOwnerSession,
  withMigrationLock,
  migrateSession,
  statusSession,
  verifySession,
  migrationChecksum,
  MigrationError,
} from '@sportify/migrations';

function requireCheck(condition) {
  if (!condition) throw new Error('Oracle runner assertion failed.');
}
try {
  const release = await loadManifest(fileURLToPath(new URL('../', import.meta.url)));
  let manifest = { ...release, migrations: release.migrations.slice(0, 11) };
  assertReady(release); // This suite cannot bypass outstanding design review.
  const reconcileStorage = process.argv[2] === '--reconcile-extended-varchar-storage';
  requireCheck(process.argv.length === (reconcileStorage ? 3 : 2));
  const config = parseMigrationConfig(process.env);
  if (
    config.ORACLE_MIGRATION_SCHEMA !== 'SPORTIFY_TEST_OWNER' ||
    process.env.ORACLE_MIGRATION_TEST_CONFIRM !== 'isolated-disposable-empty'
  ) {
    throw new Error('Disposable test prerequisites missing.');
  }
  const runtimes = runtimeVerificationConfigs(process.env); // Fail before owner mutation if either credential is missing.
  await withOwnerSession(config, async (session) => {
    if (reconcileStorage) {
      manifest = await reconcileExtendedStorageFailure(
        session,
        config.ORACLE_MIGRATION_SCHEMA,
        manifest,
      );
      console.info(
        'PASS explicit disposable storage reconciliation: full original catalog verified; FAILED 000008 retained and linked to distinct APPLIED test-only repair 000012.',
      );
    } else {
      const before = await session.execute('SELECT OBJECT_NAME FROM USER_OBJECTS');
      requireCheck((before.rows ?? []).length === 0); // No clearing/adoption of an existing schema.
    }
    const first = await migrateSession(session, config.ORACLE_MIGRATION_SCHEMA, manifest);
    requireCheck(
      first.length ===
        (reconcileStorage
          ? 3
          : manifest.migrations.filter((entry) => entry.repairOf === null).length),
    );
    requireCheck(
      (await migrateSession(session, config.ORACLE_MIGRATION_SCHEMA, manifest)).length === 0,
    );
    await verifySession(session, config.ORACLE_MIGRATION_SCHEMA, manifest);
    const status = await statusSession(session, manifest);
    const changed = structuredClone(manifest);
    changed.migrations[0].name += '_tampered';
    changed.migrations[0].checksum = migrationChecksum(
      changed.migrations[0],
      changed.migrations[0].statements,
    );
    let rejected = false;
    try {
      await migrateSession(session, config.ORACLE_MIGRATION_SCHEMA, changed);
    } catch (error) {
      rejected = error instanceof MigrationError && error.code === 'ARTIFACT_CHANGED';
    }
    requireCheck(
      rejected && (await statusSession(session, manifest)).history.length === status.history.length,
    );
    console.info(
      reconcileStorage
        ? 'PASS actual Oracle runner: explicit reconciled continuation, repeat no-op, catalog/seed metadata and modified-checksum rejection.'
        : 'PASS actual Oracle runner: clean apply, repeat no-op, catalog/seed metadata and modified-checksum rejection.',
    );
    await verifySeedRepeat(session, config.ORACLE_MIGRATION_SCHEMA, manifest);
    await verifyIntegrity(session, config.ORACLE_MIGRATION_SCHEMA, manifest);

    // This fixture is generated by this suite only, in the expressly disposable
    // owner. DDL commits must not release the held schema migration lock.
    const name = 'S7_LOCK_' + randomUUID().replaceAll('-', '').slice(0, 20).toUpperCase();
    let created = false;
    await withMigrationLock(session, config.ORACLE_MIGRATION_SCHEMA, async () => {
      try {
        await session.execute(`CREATE TABLE ${name} (ID NUMBER)`);
        created = true;
        await withOwnerSession(config, async (second) => {
          let locked = false;
          try {
            await migrateSession(second, config.ORACLE_MIGRATION_SCHEMA, manifest);
          } catch (error) {
            locked = error instanceof MigrationError && error.code === 'LOCK_UNAVAILABLE';
          }
          requireCheck(locked);
        });
      } finally {
        if (created) await session.execute(`DROP TABLE ${name} PURGE`);
      }
    });
    await verifySession(session, config.ORACLE_MIGRATION_SCHEMA, manifest);
    console.info(
      'PASS actual Oracle session lock survives DDL commit; concurrent runner denied; suite-created fixture removed.',
    );
    await verifyFailureRecovery(session, config.ORACLE_MIGRATION_SCHEMA, manifest);
    await verifyRuntimePrivileges(
      runtimes,
      config.ORACLE_MIGRATION_DB_UNIQUE_NAME,
      config.ORACLE_MIGRATION_SCHEMA,
    );
  });
  console.info(
    'PASS disposable Step 07 migration, integrity, explicit recovery and runtime-denial suite. Installed test schema and fixture history are retained. No application authentication or commercial-readiness claim.',
  );
} catch (error) {
  console.error(
    error instanceof EnvironmentError || error instanceof MigrationError
      ? error.message
      : 'Oracle runner suite FAILED or prerequisites incomplete. Requires an approved manifest, designated empty SPORTIFY_TEST_OWNER and isolated-disposable-empty confirmation. Raw diagnostics suppressed.',
  );
  process.exitCode = 1;
}
