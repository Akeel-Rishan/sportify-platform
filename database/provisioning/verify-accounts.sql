-- SQLcl read-only postcondition verification, after hidden PASSWORD and unlock.
SET ECHO OFF
SET VERIFY OFF
SET DEFINE OFF
SET SERVEROUTPUT ON
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
DECLARE
  found NUMBER;
BEGIN
  IF :expected_db_unique_name IS NULL OR :expected_db_unique_name <> SYS_CONTEXT('USERENV','DB_UNIQUE_NAME')
    OR SYS_CONTEXT('USERENV','SESSION_USER') <> 'ADMIN' THEN
    RAISE_APPLICATION_ERROR(-20010, 'STOP: target or executing administrator mismatch.');
  END IF;
  SELECT COUNT(*) INTO found FROM DBA_USERS
    WHERE USERNAME IN ('SPORTIFY_SCHEMA_OWNER','SPORTIFY_API','SPORTIFY_WORKER')
      AND ACCOUNT_STATUS = 'OPEN' AND AUTHENTICATION_TYPE = 'PASSWORD';
  IF found <> 3 THEN RAISE_APPLICATION_ERROR(-20011, 'Account authentication/status postcondition failed.'); END IF;
  SELECT COUNT(*) INTO found FROM DBA_SYS_PRIVS
    WHERE GRANTEE IN ('SPORTIFY_SCHEMA_OWNER','SPORTIFY_API','SPORTIFY_WORKER')
    AND (ADMIN_OPTION <> 'NO' OR NOT (PRIVILEGE = 'CREATE SESSION'
      OR (GRANTEE = 'SPORTIFY_SCHEMA_OWNER' AND PRIVILEGE IN ('CREATE TABLE','CREATE SEQUENCE'))));
  IF found <> 0 THEN RAISE_APPLICATION_ERROR(-20012, 'Unexpected direct system privileges/admin option.'); END IF;
  SELECT COUNT(*) INTO found FROM DBA_SYS_PRIVS WHERE
    (GRANTEE = 'SPORTIFY_SCHEMA_OWNER' AND PRIVILEGE IN ('CREATE SESSION','CREATE TABLE','CREATE SEQUENCE'))
    OR (GRANTEE IN ('SPORTIFY_API','SPORTIFY_WORKER') AND PRIVILEGE = 'CREATE SESSION');
  IF found <> 5 THEN RAISE_APPLICATION_ERROR(-20013, 'Required direct privileges missing.'); END IF;
  SELECT COUNT(*) INTO found FROM DBA_ROLE_PRIVS WHERE GRANTEE IN ('SPORTIFY_SCHEMA_OWNER','SPORTIFY_API','SPORTIFY_WORKER');
  IF found <> 0 THEN RAISE_APPLICATION_ERROR(-20014, 'Unexpected role grants.'); END IF;
  SELECT COUNT(*) INTO found FROM DBA_TAB_PRIVS WHERE GRANTEE IN ('SPORTIFY_SCHEMA_OWNER','SPORTIFY_API','SPORTIFY_WORKER');
  IF found <> 0 THEN RAISE_APPLICATION_ERROR(-20015, 'Unexpected object grants before business schema exists.'); END IF;
  SELECT COUNT(*) INTO found FROM DBA_COL_PRIVS WHERE GRANTEE IN ('SPORTIFY_SCHEMA_OWNER','SPORTIFY_API','SPORTIFY_WORKER');
  IF found <> 0 THEN RAISE_APPLICATION_ERROR(-20016, 'Unexpected column grants.'); END IF;
  SELECT COUNT(*) INTO found FROM DBA_TS_QUOTAS WHERE USERNAME = 'SPORTIFY_SCHEMA_OWNER'
    AND TABLESPACE_NAME = 'DATA' AND MAX_BYTES = :owner_quota_mb * 1024 * 1024;
  IF found <> 1 THEN RAISE_APPLICATION_ERROR(-20017, 'Owner finite DATA quota mismatch.'); END IF;
  SELECT COUNT(*) INTO found FROM DBA_TS_QUOTAS WHERE
    (USERNAME IN ('SPORTIFY_API','SPORTIFY_WORKER') AND MAX_BYTES <> 0)
    OR (USERNAME = 'SPORTIFY_SCHEMA_OWNER' AND TABLESPACE_NAME <> 'DATA' AND MAX_BYTES <> 0);
  IF found <> 0 THEN RAISE_APPLICATION_ERROR(-20018, 'Unexpected tablespace quota.'); END IF;
  SELECT COUNT(*) INTO found FROM DBA_OBJECTS WHERE OWNER IN ('SPORTIFY_SCHEMA_OWNER','SPORTIFY_API','SPORTIFY_WORKER');
  IF found <> 0 THEN RAISE_APPLICATION_ERROR(-20019, 'Unexpected objects before Step 07.'); END IF;
  DBMS_OUTPUT.PUT_LINE('PASS: account authentication, direct grants, roles, object/column grants, quotas and empty schemas.');
  DBMS_OUTPUT.PUT_LINE('PENDING: administrator must review inherited PUBLIC grants against the target baseline.');
END;
/
-- Read-only review: indirect PUBLIC rights are target-specific and not silently
-- revoked. Securely review these with the ATP baseline, including role grants.
SELECT PRIVILEGE, ADMIN_OPTION FROM DBA_SYS_PRIVS WHERE GRANTEE = 'PUBLIC';
SELECT GRANTED_ROLE, ADMIN_OPTION FROM DBA_ROLE_PRIVS WHERE GRANTEE = 'PUBLIC';
