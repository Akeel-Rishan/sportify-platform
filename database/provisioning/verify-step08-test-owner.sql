-- Before first disposable suite run only. Installed test schemas are retained.
SET ECHO OFF
SET VERIFY OFF
SET DEFINE OFF
SET SERVEROUTPUT ON
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
DECLARE
  found NUMBER;
BEGIN
  IF :expected_db_unique_name IS NULL OR :expected_db_unique_name<>SYS_CONTEXT('USERENV','DB_UNIQUE_NAME')
    OR SYS_CONTEXT('USERENV','SESSION_USER')<>'ADMIN' THEN
    RAISE_APPLICATION_ERROR(-20050,'STOP: verified target and ADMIN required.');
  END IF;
  SELECT COUNT(*) INTO found FROM DBA_USERS WHERE USERNAME='SPORTIFY_STEP08_TEST_OWNER' AND ACCOUNT_STATUS='OPEN' AND AUTHENTICATION_TYPE='PASSWORD';
  IF found<>1 THEN RAISE_APPLICATION_ERROR(-20051,'Test-owner authentication/status failed.'); END IF;
  SELECT COUNT(*) INTO found FROM DBA_SYS_PRIVS WHERE GRANTEE='SPORTIFY_STEP08_TEST_OWNER';
  IF found<>3 THEN RAISE_APPLICATION_ERROR(-20052,'Unexpected test-owner system privileges.'); END IF;
  SELECT COUNT(*) INTO found FROM DBA_SYS_PRIVS WHERE GRANTEE='SPORTIFY_STEP08_TEST_OWNER' AND ADMIN_OPTION='NO' AND PRIVILEGE IN ('CREATE SESSION','CREATE TABLE','CREATE SEQUENCE');
  IF found<>3 THEN RAISE_APPLICATION_ERROR(-20053,'Missing or excessive test-owner system privileges.'); END IF;
  SELECT COUNT(*) INTO found FROM DBA_ROLE_PRIVS WHERE GRANTEE='SPORTIFY_STEP08_TEST_OWNER';
  IF found<>0 THEN RAISE_APPLICATION_ERROR(-20054,'Unexpected test-owner roles.'); END IF;
  SELECT COUNT(*) INTO found FROM DBA_TAB_PRIVS WHERE GRANTEE='SPORTIFY_STEP08_TEST_OWNER';
  IF found<>1 THEN RAISE_APPLICATION_ERROR(-20055,'Unexpected test-owner object grants.'); END IF;
  SELECT COUNT(*) INTO found FROM DBA_TAB_PRIVS WHERE GRANTEE='SPORTIFY_STEP08_TEST_OWNER' AND OWNER='SYS' AND TABLE_NAME='DBMS_LOCK' AND PRIVILEGE='EXECUTE' AND GRANTABLE='NO';
  IF found<>1 THEN RAISE_APPLICATION_ERROR(-20056,'Missing exact test-owner lock capability.'); END IF;
  SELECT COUNT(*) INTO found FROM DBA_COL_PRIVS WHERE GRANTEE='SPORTIFY_STEP08_TEST_OWNER';
  IF found<>0 THEN RAISE_APPLICATION_ERROR(-20057,'Unexpected column grants.'); END IF;
  SELECT COUNT(*) INTO found FROM DBA_TS_QUOTAS WHERE USERNAME='SPORTIFY_STEP08_TEST_OWNER' AND TABLESPACE_NAME='DATA' AND MAX_BYTES=:owner_quota_mb*1024*1024;
  IF found<>1 THEN RAISE_APPLICATION_ERROR(-20058,'Test-owner finite quota mismatch.'); END IF;
  SELECT COUNT(*) INTO found FROM DBA_TS_QUOTAS WHERE USERNAME='SPORTIFY_STEP08_TEST_OWNER' AND TABLESPACE_NAME<>'DATA' AND MAX_BYTES<>0;
  IF found<>0 THEN RAISE_APPLICATION_ERROR(-20059,'Unexpected additional quota.'); END IF;
  SELECT COUNT(*) INTO found FROM DBA_OBJECTS WHERE OWNER='SPORTIFY_STEP08_TEST_OWNER';
  IF found<>0 THEN RAISE_APPLICATION_ERROR(-20060,'Test owner must initially be genuinely empty; never clear it automatically.'); END IF;
  DBMS_OUTPUT.PUT_LINE('PASS: initial disposable test-owner identity, exact grants, quota and empty schema.');
END;
/
