"""Read-only checks of the restricted authored Step 08 artifact format.

This checks design/manifest/SQL agreement, not Oracle compilation or enforcement.
It neither executes SQL nor splits scripts into executable statements.
"""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[2]
DB = ROOT / "database"
DOC = ROOT / "Docs/database"


def sections(text, level):
    mark = "#" * level
    return dict(re.findall(r"^" + mark + r" ([A-Z][A-Z_]+)\n(.*?)(?=^" + mark + r" |\Z)", text, re.M | re.S))


def cells(line):
    return [part.strip().strip("`") for part in line.strip().strip("|").split("|")]


def canonical(sql):
    return "".join(token if token.startswith("'") else token.upper()
                   for token in re.findall(r"'(?:''|[^'])*'|[^\s]", sql))


manifest = json.loads((DB / "migrations/manifest.json").read_text(encoding="utf-8"))
dictionary = sections((DOC / "data-dictionary.md").read_text(encoding="utf-8"), 2)
register = (DOC / "relationships-and-constraints.md").read_text(encoding="utf-8")
checks = sections(register, 3)
index_plan = sections((DOC / "index-plan.md").read_text(encoding="utf-8"), 2)
entries = manifest["migrations"][:17]
assert len(entries) == 17, "Six Step 08 forward phases required."
tables = {table["name"]: table for entry in entries for table in entry["tables"]}
expected = set("SCHEMA_MIGRATIONS TENANTS USERS TENANT_USERS AUTH_SESSIONS EMAIL_VERIFICATION_TOKENS PASSWORD_RESET_TOKENS PLATFORM_ADMINS ROLES PERMISSIONS ROLE_PERMISSIONS USER_ROLES STAFF_ASSIGNMENTS TENANT_INVITATIONS BUSINESSES BUSINESS_PROFILES LOCATIONS SPORTS BUSINESS_SPORTS RESOURCES RESOURCE_FEATURES OPERATING_HOURS HOLIDAYS AVAILABILITY_BLOCKS PRICING_RULES INVITATION_LOCATIONS CUSTOMERS BUSINESS_PAYMENT_SETTINGS BOOKING_HOLDS BOOKING_HOLD_ITEMS BOOKINGS BOOKING_ITEMS RESOURCE_SLOT_RESERVATIONS BOOKING_CANCELLATIONS PAYMENTS REFUNDS".split())
assert set(tables) == expected and len(tables) == 36
assert sum(len(entry["tables"]) for entry in entries) == len(tables), "No duplicate table declarations."
artifacts = [(item, (DB / item["path"]).read_text(encoding="utf-8")) for entry in entries for item in entry["files"]]
sql = "\n".join(text for _, text in artifacts)
assert not re.search(r"\b(?:CASCADE|DEFERRABLE|DISABLE|NOVALIDATE)\b", sql, re.I), "Unapproved FK deletion/constraint-state change."
assert {name.upper() for name in re.findall(r"^CREATE TABLE ([A-Z_]+) \(", sql, re.M | re.I)} == expected
assert [entry["version"] for entry in entries] == [f"{i:06d}" for i in range(1, len(entries) + 1)]

for name, table in tables.items():
    rows = [cells(line) for line in dictionary[name].splitlines()]
    rows = [row for row in rows if len(row) == 8 and re.fullmatch(r"[A-Z][A-Z0-9_]+", row[0])]
    expected_columns = [dict(name=row[0], type=row[1], nullable=row[2] == "Y",
                             default=None if row[3] in ("none", "IDENTITY BY DEFAULT ON NULL") else row[3],
                             identity=row[3] == "IDENTITY BY DEFAULT ON NULL") for row in rows]
    assert table["columns"] == expected_columns, f"Dictionary/manifest mismatch: {name}"
    bodies = [text for _, text in artifacts if re.match(r"CREATE TABLE " + name + r" \(", text, re.I)]
    assert len(bodies) == 1
    lines = [line.strip().rstrip(",") for line in bodies[0].splitlines()[1:-1]]
    column_lines = [line for line in lines if not line.startswith("CONSTRAINT ")]
    assert len(column_lines) == len(expected_columns), f"Unexpected SQL columns: {name}"
    for column, actual in zip(expected_columns, column_lines):
        wanted = column["name"] + " " + column["type"]
        if column["identity"]:
            wanted += " GENERATED BY DEFAULT ON NULL AS IDENTITY"
        elif column["default"] is not None:
            wanted += " DEFAULT " + column["default"]
        if not column["nullable"]:
            wanted += " NOT NULL"
        assert canonical(actual) == canonical(wanted), f"SQL column mismatch: {name}.{column['name']}"

constraints = {constraint["name"]: constraint for entry in entries for constraint in entry["constraints"]}
assert len(constraints) == sum(len(entry["constraints"]) for entry in entries)
expected_constraints = {}
for line in register.splitlines():
    row = cells(line)
    if len(row) == 7 and row[0] in expected and row[2] in ("PK", "UK", "FK"):
        table, name, kind, columns, parent, targets, _ = row
        expected_constraints[name] = dict(name=name, table=table, type={"PK": "P", "UK": "U", "FK": "R"}[kind],
            columns=[part.strip() for part in columns.split(",")], referencedTable=parent if kind == "FK" else None,
            referencedColumns=[part.strip() for part in targets.split(",")] if kind == "FK" else [], expression=None)
for table in expected:
    for name, expression in re.findall(r"^- `([A-Z0-9_]+)` \((?:source|proposed|approved)\): `CHECK \((.*)\)`\s*$", checks[table], re.M):
        expected_constraints[name] = dict(name=name, table=table, type="C", columns=[], referencedTable=None,
                                          referencedColumns=[], expression=expression)
assert constraints == expected_constraints, "Constraint register/manifest mismatch."
actual_names = re.findall(r"\bCONSTRAINT ([A-Z][A-Z0-9_]+)\b", sql, re.I)
assert len(actual_names) == len(set(actual_names)) and set(actual_names) == set(constraints)
canonical_artifacts = [canonical(text) for _, text in artifacts]
for name, constraint in constraints.items():
    kind = constraint["type"]
    if kind == "C":
        wanted = f"CONSTRAINT {name} CHECK ({constraint['expression']})"
    else:
        wanted = f"CONSTRAINT {name} " + {"P": "PRIMARY KEY", "U": "UNIQUE", "R": "FOREIGN KEY"}[kind]
        wanted += " (" + ", ".join(constraint["columns"]) + ")"
        if kind == "R":
            assert constraint["referencedTable"] in expected
            wanted += " REFERENCES " + constraint["referencedTable"] + " (" + ", ".join(constraint["referencedColumns"]) + ")"
    assert any(canonical(wanted) in actual for actual in canonical_artifacts), f"SQL constraint mismatch: {name}"

indexes = {index["name"]: index for entry in entries for index in entry["indexes"]}
planned = {}
for table in expected:
    for line in index_plan[table].splitlines():
        row = cells(line)
        if len(row) == 5 and row[1] in ("Y", "N") and "backing key" not in row[0]:
            planned[row[0]] = dict(name=row[0], table=table, unique=row[1] == "Y", expressions=[part.strip().upper() for part in row[2].split(",")])
assert indexes == planned, "Index plan/manifest mismatch."
for name, index in indexes.items():
    wanted = "CREATE " + ("UNIQUE " if index["unique"] else "") + "INDEX " + name + " ON " + index["table"] + " (" + ", ".join(index["expressions"]) + ")"
    assert canonical(wanted) in canonical_artifacts, f"SQL index mismatch: {name}"
for entry in entries:
    if entry["kind"] == "seed":
        for item in entry["files"]:
            text = (DB / item["path"]).read_text(encoding="utf-8")
            assert re.match(r"MERGE INTO (SPORTS|PERMISSIONS)\b", text, re.I)
            assert "WHEN MATCHED" not in text.upper(), "Do not overwrite customized reference data."
            assert "WHEN NOT MATCHED" in text.upper()
            codes = re.findall(r"SELECT\s+'([^']+)'", text, re.I)
            assert len(codes) == len(set(codes))
            assert codes == entry["seeds"][0]["values"], "Seed source/manifest natural-key mismatch."

slot_pk = constraints['PK_RESOURCE_SLOT_RESERVATIONS']
assert slot_pk['columns'] == ['TENANT_ID', 'RESOURCE_ID', 'SLOT_START_UTC']
assert all(not c['nullable'] for c in tables['RESOURCE_SLOT_RESERVATIONS']['columns'] if c['name'] in slot_pk['columns'])
assert constraints['FK_SLOTS_BOOKING_ITEM']['columns'] == ['TENANT_ID','BOOKING_ITEM_ID','RESOURCE_ID']
assert constraints['FK_SLOT_RESERVATIONS_HOLD_ITEM']['columns'] == ['TENANT_ID','HOLD_ITEM_ID','RESOURCE_ID']
assert indexes['UX_BOOKINGS_SOURCE_HOLD']['unique']
assert all('IS NOT NULL THEN' in value for value in indexes['UX_BOOKINGS_SOURCE_HOLD']['expressions'])
assert not any(re.search(r'\b(SYSDATE|SYSTIMESTAMP|CURRENT_TIMESTAMP)\b', c['expression'] or '', re.I) for c in constraints.values())
assert 'PAYMENT_TRANSACTIONS' not in tables

print(f"PASS static Step 08 {manifest['status']} release agreement: {len(entries)} phases, {len(tables)} tables, {len(constraints)} named constraints, {len(indexes)} explicit indexes; no out-of-scope objects or duplicate table declarations.")
print("STATIC ONLY: this script does not execute Oracle SQL, locking, concurrency or privilege tests. Separate actual live results are recorded in Docs/database/step08-verification.md.")
