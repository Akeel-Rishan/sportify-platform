CREATE TABLE resources (
    resource_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    tenant_id           NUMBER NOT NULL,
    business_id         NUMBER NOT NULL,
    location_id         NUMBER NOT NULL,
    sport_id            NUMBER NOT NULL,
    resource_code       VARCHAR2(50 CHAR) NOT NULL,
    resource_name       VARCHAR2(160 CHAR) NOT NULL,
    resource_type       VARCHAR2(50 CHAR) NOT NULL,
    description         VARCHAR2(2000 CHAR),
    capacity            NUMBER(6),
    slot_interval_minutes NUMBER(3) DEFAULT 15 NOT NULL,
    minimum_duration_minutes NUMBER(4) DEFAULT 60 NOT NULL,
    maximum_duration_minutes NUMBER(4) DEFAULT 180 NOT NULL,
    advance_booking_days NUMBER(4) DEFAULT 30 NOT NULL,
    buffer_before_minutes NUMBER(4) DEFAULT 0 NOT NULL,
    buffer_after_minutes NUMBER(4) DEFAULT 0 NOT NULL,
    is_bookable         CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    resource_status     VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    created_at_utc      TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    updated_at_utc      TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT pk_resources PRIMARY KEY (resource_id),
    CONSTRAINT uq_resources_tenant_id UNIQUE (tenant_id, resource_id),
    CONSTRAINT uq_res_tenant_loc_id UNIQUE (tenant_id, location_id, resource_id),
    CONSTRAINT uq_res_biz_loc_id UNIQUE (tenant_id, business_id, location_id, resource_id),
    CONSTRAINT uq_resources_location_code UNIQUE (tenant_id, location_id, resource_code),
    CONSTRAINT fk_resources_business FOREIGN KEY (tenant_id, business_id) REFERENCES businesses(tenant_id, business_id),
    CONSTRAINT fk_resources_location FOREIGN KEY (tenant_id, business_id, location_id) REFERENCES locations(tenant_id, business_id, location_id),
    CONSTRAINT fk_resources_business_sport FOREIGN KEY (tenant_id, business_id, sport_id) REFERENCES business_sports(tenant_id, business_id, sport_id),
    CONSTRAINT ck_resources_slot_interval CHECK (slot_interval_minutes = 15),
    CONSTRAINT ck_resources_durations CHECK (minimum_duration_minutes > 0 AND maximum_duration_minutes >= minimum_duration_minutes AND MOD(minimum_duration_minutes,15) = 0 AND MOD(maximum_duration_minutes,15) = 0),
    CONSTRAINT ck_resources_capacity CHECK (capacity IS NULL OR capacity > 0),
    CONSTRAINT ck_resources_bookable CHECK (is_bookable IN ('Y','N')),
    CONSTRAINT ck_resources_status CHECK (resource_status IN ('ACTIVE','INACTIVE','MAINTENANCE','CLOSED'))
);
CREATE INDEX ix_resources_tenant_location ON resources(tenant_id, location_id, resource_status);
