    timezone_name       VARCHAR2(64 CHAR) DEFAULT 'Asia/Colombo' NOT NULL,
    default_language    VARCHAR2(10 CHAR) DEFAULT 'en' NOT NULL,
    created_at_utc      TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    updated_at_utc      TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    deleted_at_utc      TIMESTAMP(6),
