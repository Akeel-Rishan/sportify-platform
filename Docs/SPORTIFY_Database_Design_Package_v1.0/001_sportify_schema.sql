-- ============================================================================
-- SPORTIFY - Oracle Autonomous Transaction Processing schema
-- Schema version: 1.0.0
-- Target: Oracle Database 19c-compatible SQL (verify against selected ADB release)
-- Model: Shared-schema, multi-tenant SaaS
--
-- IMPORTANT IMPLEMENTATION NOTES
-- 1. Run once against a dedicated empty application schema, not ADMIN.
-- 2. All *_UTC columns are TIMESTAMP(6) WITHOUT TIME ZONE and MUST contain UTC.
--    The application must convert to/from the tenant's IANA timezone. Every
--    pooled database session MUST execute ALTER SESSION SET TIME_ZONE = 'UTC';
--    LOCALTIMESTAMP defaults are therefore UTC wall-clock values.
-- 3. Tenant-owned child tables carry TENANT_ID and use composite tenant-aware FKs.
-- 4. RESOURCE_SLOT_RESERVATIONS has one row per active 15-minute resource slot.
--    Its PK is the final overlap/concurrency guard. Delete rows transactionally
--    when a hold expires or a booking is cancelled; retain the parent history.
-- 5. Do not cascade-delete bookings, payments, customers, tenants or audit history.
-- 6. This file is a bootstrap DDL, not an idempotent migration. Use versioned
--    migrations for subsequent changes.
-- 7. Review names, sizes, retention and access grants with the implementation
--    team before production deployment.
-- ============================================================================

